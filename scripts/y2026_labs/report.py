#!/usr/bin/env python3
"""results/y2026_labs/{discovered,analysis}.json + tokens/*.json + findings.md -> LABS2026.md"""
import json
import pathlib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[2]
D = ROOT / "results" / "y2026_labs"
CLS = ["token record", "record, poor fit", "changed throughout", "not comparable", "unchanged", "shared matrix"]
PLAIN = {"token record": "some token vectors bit-identical to the parent after removing a uniform shrink, and the shrink fit reproduces >= 99% of numbers",
         "record, poor fit": "some vectors bit-identical, but the shrink fit reproduces < 99% (treat token lists with care)",
         "changed throughout": "every token vector changed; still consistent with the parent plus weight decay",
         "not comparable": "not a decayed copy of that parent (re-initialised, rescaled or a different starting point)",
         "shared matrix": "one matrix shared by input and output (tied): every vector trains, no record",
         "unchanged": "embedding unchanged"}


def safe(key):
    return key.replace("/", "__").replace(" -> ", "--").replace("@", "_")


def tok_summary(key):
    f = D / "tokens" / (safe(key) + ".json")
    if not f.exists():
        return None
    t = json.load(open(f))
    if t.get("status") != "ok":
        return dict(status=t.get("status"))
    sp = t.get("added_tokens", [])
    named = [s for s in sp if not any(x in s["content"].lower() for x in ("reserved", "placeholder", "unused", "<extra_id"))]
    st = Counter(s["state"] for s in named)
    return dict(status="ok", named=dict(st), n_named=len(named))


def main():
    disc = json.load(open(D / "discovered.json"))
    an = json.load(open(D / "analysis.json"))
    L = ["# 2026 lab releases: what their token vectors show", "",
         "Generated by `scripts/y2026_labs/report.py`. Comparisons are base -> released model where a base is published, otherwise",
         "the previous release in the same line, plus 2026 releases whose model card names a base model. Same pipeline and checks as",
         "`results/frontier_x`: input embeddings only, exact 16-bit diff after removing a fitted uniform shrink (weight decay),",
         "comparability class, share of changed numbers per token vector (detection floor), special-token states, token categories",
         "(`scripts/tokens`), and the exact total-weight-decay interval where vectors were only shrunk.", "",
         "Wording follows STYLE.md: *bit-identical to the parent* is an observation about the released weights. Nothing here says",
         "anything about intent.", ""]
    fd = D / "findings.md"
    if fd.exists():
        L += [fd.read_text(), ""]
    L += ["## Comparisons", "",
          "| parent -> release | relation | class | bit-identical tokens | barely changed (<=1% of numbers) | vectors with 0-10% of numbers changed | total weight decay: vectors shrank by | named special tokens |",
          "|---|---|---|---|---|---|---|---|"]
    for r in sorted(an, key=lambda r: (CLS.index(r["cls"]), r["child"])):
        h = r.get("change_hist") or []
        low = (h[1] + h[2]) if len(h) >= 3 else None
        sh = r.get("shrink_pct")
        if sh:
            shs = f"{sh[0]:.2f}-{sh[1]:.2f}%"
        elif r["cls"] == "token record" and abs((r.get("P") or 0) - 1) < 1e-9:
            shs = "no shrink"
        else:
            shs = "-"
        ts = tok_summary(r["key"])
        sps = "-"
        if ts and ts.get("status") == "ok":
            sps = ", ".join(f"{k} {v}" for k, v in sorted(ts["named"].items())) or "-"
        lows = "" if low is None else f"{100 * low:.1f}%"
        L.append(f"| {r['parent']} -> {r['child']} | {r['relation']} | {r['cls']} | {r['bit_identical']:,} | "
                 f"{r['barely']:,} | {lows} | {shs} | {sps} |")
    c = Counter(r["cls"] for r in an)
    L += ["", "Classes: " + "; ".join(f"**{k}**: {v}" for k, v in PLAIN.items()), "",
          "Counts: " + ", ".join(f"{k} {c.get(k, 0)}" for k in CLS), ""]
    L += ["## 2026 releases found (text / vision-language, >= 3B parameters)", "",
          "From the Hugging Face API (`scripts/y2026_labs/discover.py`, created on or after 2026-01-01; quantized, draft and",
          "embedding repos filtered out). Gated repos (e.g. Cohere tiny-aya, Apertus v1.5, Meta) cannot be fetched anonymously.", "",
          "| created | repo | params (B) | downloads |", "|---|---|---|---|"]
    keep = [x for x in disc if x["pipeline"] in ("text-generation", "image-text-to-text", None) and (x["params"] or 0) >= 3e9]
    for x in sorted(keep, key=lambda x: (x["id"].split("/")[0].lower(), x["created"])):
        L.append(f"| {x['created']} | [{x['id']}](https://huggingface.co/{x['id']}) | {x['params'] / 1e9:.0f} | {x['downloads']:,} |")
    sk = json.load(open(D / "skipped.json"))
    L += ["", "## Candidates not compared", "", "| parent -> release | reason |", "|---|---|"]
    L += [f"| {s['parent']} -> {s['child']} | {s['why'][:140]} |" for s in sk]
    (D / "LABS2026.md").write_text("\n".join(L) + "\n")
    print("wrote", D / "LABS2026.md")


if __name__ == "__main__":
    main()
