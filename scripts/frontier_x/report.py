#!/usr/bin/env python3
"""results/roster/sweep_frontier_x.jsonl -> results/frontier_x/{frontier_x.json, FRONTIER_X.md}.

Classification follows scripts/frontier/comparability.py (fit = the sweep's check of its fitted
shrink factor: fraction of numbers, in the 512 vectors closest to a pure shrink, that
round(P*base) reproduces exactly).
"""
import json, math, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "frontier"))
from comparability import classify  # noqa

NAMED = ("<|", "<｜", "<think", "</think", "<tool", "</tool", "[INST", "[/INST", "<start", "<end", "<im_", "<|im", "[gMASK", "<sop", "<eop", "<|user", "<|assistant", "<|system", "<|observation")


def is_reserved(c):
    c = (c or "").lower()
    return any(k in c for k in ("reserved", "placeholder", "unused", "<|extra_", "special_token_", "<|place", "place▁holder", "<special_", "<|reserved"))


def main():
    recs = {}
    for l in open(ROOT / "results" / "roster" / "sweep_frontier_x.jsonl"):
        r = json.loads(l)
        if r.get("status") == "ok" or r["key"] not in recs:
            recs[r["key"]] = r
    pairs = json.load(open(ROOT / "results" / "frontier_x" / "pairs_x.json"))
    skipped = json.load(open(ROOT / "results" / "frontier_x" / "skipped_x.json"))
    rows = []
    for r in recs.values():
        if r.get("status") != "ok":
            rows.append(dict(parent=r["parent"], child=r["child"], cls="error", error=r.get("error", r.get("status"))[:160]))
            continue
        e = r["embed"]
        sp = r.get("special") or []
        named = [t for t in sp if not is_reserved(t["content"])]
        res = [t for t in sp if is_reserved(t["content"])]
        cnt = lambda L, s: sum(t["state"] == s for t in L)
        h = r.get("change_hist", {})
        rows.append(dict(parent=r["parent"], child=r["child"], relation=r.get("relation"), cls=classify(r),
                         vocab=e["rows"], bit_identical_raw=e["identical"], bit_identical_after_decay=e["unmoved"],
                         barely_changed=e["near"], changed=e["moved"], P=e["P"], shrink_pct=100 * (1 - e["P"]),
                         fit=e["P_exact_frac"], hist_labels=h.get("labels"), hist_frac=h.get("frac"),
                         named_special=dict(n=len(named), updated=cnt(named, "moved"), barely=cnt(named, "near"), identical=cnt(named, "unmoved")),
                         reserved=dict(n=len(res), updated=cnt(res, "moved"), barely=cnt(res, "near"), identical=cnt(res, "unmoved")),
                         named_identical=[t["content"] for t in named if t["state"] == "unmoved"][:40],
                         named_updated=[t["content"] for t in named if t["state"] == "moved"][:40],
                         unmoved_ranges=r.get("unmoved_ranges", [])[:8], tied=r.get("tied")))
    json.dump(dict(rows=rows, skipped=skipped), open(ROOT / "results" / "frontier_x" / "frontier_x.json", "w"), indent=1)
    order = ["token record", "record, poor fit", "changed throughout", "not comparable", "unchanged", "shared matrix", "error"]
    rows.sort(key=lambda x: (order.index(x["cls"]), x["child"]))
    f = lambda v, n=4: "-" if v is None or (isinstance(v, float) and math.isnan(v)) else (f"{v:.{n}g}" if isinstance(v, float) else str(v))
    L = ["# Frontier comparisons added (frontier_x)", "",
         "Generated by `scripts/frontier_x/report.py` from `results/roster/sweep_frontier_x.jsonl`. Each line compares a",
         "released model with its published base (or, where no base is published, with the previous release).",
         "Wording follows STYLE.md.", "",
         "Columns: **bit-identical** = token vectors equal to the base after removing a uniform shrink (weight decay);",
         "**barely changed** = under 1% of the vector's numbers differ; **fit** = share of numbers the fitted shrink",
         "reproduces in the 512 most shrink-like vectors (comparable to that base if >= 0.99);",
         "**change histogram** = share of token vectors whose numbers differ by 0 / <=1% / 1-10% / 10-50% / >50%.", "",
         "| class | base / previous | release | vocab | bit-identical | barely changed | shrink | fit | change histogram | named special tokens updated / barely / identical | reserved slots updated / barely / identical |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for x in rows:
        if x["cls"] == "error":
            L.append(f"| error | {x['parent']} | {x['child']} | {x['error']} |||||||| ")
            continue
        hf = "/".join(f"{100*v:.0f}" for v in x["hist_frac"]) + "%" if x["hist_frac"] else "-"
        ns, rs = x["named_special"], x["reserved"]
        L.append(f"| {x['cls']} | {x['parent']} | {x['child']} | {x['vocab']:,} | {x['bit_identical_after_decay']:,} | {x['barely_changed']:,} | "
                 f"{x['shrink_pct']:.4f}% | {f(x['fit'])} | {hf} | {ns['updated']}/{ns['barely']}/{ns['identical']} of {ns['n']} | "
                 f"{rs['updated']}/{rs['barely']}/{rs['identical']} of {rs['n']} |")
    L += ["", "## Not run", "", "| base / previous | release | why |", "|---|---|---|"]
    for s in skipped:
        L.append(f"| {s['parent']} | {s['child']} | {s['why']} |")
    fd = ROOT / "results" / "frontier_x" / "findings.md"
    if fd.exists():
        L += [""] + fd.read_text().splitlines()
    (ROOT / "results" / "frontier_x" / "FRONTIER_X.md").write_text("\n".join(L) + "\n")
    from collections import Counter
    print(Counter(x["cls"] for x in rows))


if __name__ == "__main__":
    main()
