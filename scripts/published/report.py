#!/usr/bin/env python3
"""results/published/*.json -> results/published/PUBLISHED.md"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "published"

MODELS = [  # child, data, base, data source and training code
    ("simplescaling/s1-32B", "s1", "Qwen/Qwen2.5-32B-Instruct",
     "simplescaling/s1K_tokenized `text`; github.com/simplescaling/s1 train/sft.py + sft.sh (trl SFTTrainer, block_size 32768)"),
    ("simplescaling/s1.1-32B", "s1.1", "Qwen/Qwen2.5-32B-Instruct",
     "simplescaling/s1K-1.1_tokenized `text`; same code, block size 20000 per the s1 README"),
    ("NovaSky-AI/Sky-T1-32B-Preview", "skyt1", "Qwen/Qwen2.5-32B-Instruct",
     "NovaSky-AI/Sky-T1_data_17k; model card: LLaMA-Factory (template qwen, cutoff 16384 assumed)"),
    ("bespokelabs/Bespoke-Stratos-32B", "stratos", "Qwen/Qwen2.5-32B-Instruct",
     "bespokelabs/Bespoke-Stratos-17k; model card: LLaMA-Factory (template qwen, cutoff 16384 assumed)"),
    ("bespokelabs/Bespoke-Stratos-7B", "stratos", "Qwen/Qwen2.5-7B-Instruct", "as Bespoke-Stratos-32B"),
    ("open-thoughts/OpenThinker-7B", "ot114k", "Qwen/Qwen2.5-7B-Instruct",
     "open-thoughts/OpenThoughts-114k; model card: LLaMA-Factory (template qwen, cutoff 16384 assumed)"),
]


EXTRA_CHILDREN: set = set()  # extended by a local, unpublished module
EXTRA_VERDICT: dict = {}


def load(p):
    p = OUT / p
    return json.load(open(p)) if p.exists() else None


def main(extra_models=()):
    L = ["# Published fine-tunes vs their published training data", "",
         "Generated by `scripts/published/report.py` from the JSON files in this directory.", "",
         "**Question.** A token that appears in a training input (at any position but the last of its sequence) gets a",
         "gradient through the forward pass, even when the loss on it is masked; a token that never appears gets none.",
         "With a trainable input embedding, the set of vocabulary tokens whose vectors changed between the base model",
         "and the fine-tune should therefore equal the set of tokens in the training data. We test that for well-known",
         "fine-tunes whose training data is published. Counts are distinct vocabulary tokens, not amounts of text.", "",
         "**Method.** Input-embedding tensors of the base and the fine-tune are read with ranged requests. A token vector",
         "counts as changed if any of its numbers differs from round(P x base) in the release format, with P the uniform",
         "weight-decay shrink that reproduces the most vectors (P = 1 for every model here, i.e. no visible decay). The",
         "data is tokenized with each project's own training code: trl SFTTrainer on the `text` column for s1; for the",
         "LLaMA-Factory projects, `_encode_supervised_example` from llamafactory 0.9.2.dev0 (template `qwen`),",
         "with the system prompt from the data or the framework default, and the cutoff",
         "length. The last position of each sequence is excluded (it receives no gradient; see the control).", "",
         "| fine-tune | release | tokens in data | vectors changed | in data and changed | in data, bit-identical | changed, not in data | verdict |",
         "|---|---|---|---|---|---|---|---|"]
    verdict = {
        "simplescaling/s1-32B": "**exact match**",
        "simplescaling/s1.1-32B": "**exact match** at the documented 20,000-token block size",
        "NovaSky-AI/Sky-T1-32B-Preview": "**exact match**",
        "bespokelabs/Bespoke-Stratos-32B": "**exact match**",
        "bespokelabs/Bespoke-Stratos-7B": "**exact match**",
        "open-thoughts/OpenThinker-7B": "**exact match** with the framework's default system prompt (8 tokens off with the dataset's)",
    }
    verdict.update(EXTRA_VERDICT)
    best_variant = {"open-thoughts/OpenThinker-7B": "lf_default_16384_nonfinal"}
    LT = ["| fine-tune | release | tokens in data | vectors changed | in data and changed | in data, bit-identical | changed, not in data | verdict |",
          "|---|---|---|---|---|---|---|---|"]
    for child, data, base, src in list(MODELS) + list(extra_models):
        T = LT if child in EXTRA_CHILDREN else L
        r = load(f"{child.replace('/', '__')}__{data}.json")
        if not r:
            T.append(f"| {child} | - | - | - | - | - | - | not run |")
            continue
        m = r["variants"][best_variant.get(child, "main")]
        T.append(f"| {child} | {r['dtype'].replace('torch.', '')} | {m['present']:,} | {m['changed']:,} | {m['present_and_changed']:,} | "
                 f"{m['present_not_changed']:,} | {m['changed_not_present']:,} | {verdict.get(child, '')} |")
    # control
    c = load("control.json")
    if c:
        L += ["", "## Control: our own fine-tunes, data known exactly", "",
              "Same pipeline on runs from `results/controlled` (Pythia-160m on Alpaca), comparing the fp32 result and its",
              "16-bit casts with the base. The last token of each sequence never changes: nothing attends to it and it has",
              "no next-token target, so it gets no gradient. Counting all positions leaves 68 such tokens 'in data, unchanged';",
              "excluding last positions leaves none.", "",
              "| run | release | weight decay | fitted P | tokens in data (excl. last position) | changed | changed, not in data | in data, unchanged |",
              "|---|---|---|---|---|---|---|---|"]
        for x in c:
            L.append(f"| {x['run']} | {x['release']} | {x['wd']} | {x['P']:.6f} | {x['nonfinal_present']:,} | {x['changed']:,} | "
                     f"{x['nonfinal_changed_not_present']} | {x['nonfinal_present_not_changed']} |")
        L += ["", "Zero tokens changed-but-absent in every control. The few in-data-but-unchanged tokens in the 16-bit",
              "casts with weight decay are updates smaller than half a 16-bit step (the detection floor)."]
    # s1.1 cutoff
    cu = load("cutoff_simplescaling__s1.1-32B.json")
    if cu:
        L += ["", "## s1.1: the weights give the training context length", "",
              f"Counting the full texts, {cu['not_updated']} tokens of s1K-1.1 are bit-identical in s1.1-32B. Every one of them first",
              f"appears at position {cu['not_updated_min_earliest']:,} or later in its sequence, and every changed token appears by",
              f"position {cu['updated_max_earliest']:,}. So training saw at most the first 19,902-20,022 tokens of each sequence,",
              "consistent with the block size of 20,000 the s1 README gives for s1.1 (s1 used 32,768; none of its texts is",
              f"longer). {cu['docs_over']['20000']} of the 1,000 s1.1 sequences are longer than 20,000 tokens."]
    (OUT / "PUBLISHED.md").write_text("\n".join(L) + "\n")
    return LT


if __name__ == "__main__":
    main()
