#!/usr/bin/env python3
"""LIMO / LIMO-v2 section -> PUBLISHED_LIMO.md (also regenerates PUBLISHED.md)."""
import json, pathlib
import report
from report import ROOT, OUT, load

EXTRA = [("GAIR/LIMO", "limo", "Qwen/Qwen2.5-32B-Instruct", "GAIR/LIMO (817 examples)"),
         ("GAIR/LIMO-v2", "limo2", "Qwen/Qwen2.5-32B-Instruct", "GAIR/LIMO-v2 (800 examples)")]
report.EXTRA_CHILDREN.update(c for c, *_ in EXTRA)
report.EXTRA_VERDICT.update({"GAIR/LIMO": "**not explained by the published data** (see below)", "GAIR/LIMO-v2": "close: 279 changed tokens not explained (see below)"})


def main():
    LT = report.main(EXTRA)
    # LIMO: separate file so a public commit can leave it out
    L = ["# LIMO and LIMO-v2 vs their published training data", "",
         "Generated by `scripts/published/report.py`; method, tokenization and the control are described in PUBLISHED.md.", ""] + LT
    for child, tag in (("GAIR/LIMO", "LIMO (v1)"), ("GAIR/LIMO-v2", "LIMO-v2")):
        name = child.replace("/", "__")
        r = load(f"{name}__{'limo' if child == 'GAIR/LIMO' else 'limo2'}.json")
        sz, bd, os_ = load(f"size_{name}.json"), load(f"boundary_{name}.json"), load(f"other_sets_{name}.json")
        if not r:
            continue
        m = r["variants"]["main"]
        L += ["", f"## {tag}: changed tokens the published data does not explain", "",
              f"{m['changed']:,} token vectors changed; the published set contains {m['present']:,} tokens, all but "
              f"{m['present_not_changed']} of which changed. {m['changed_not_present']:,} changed tokens do not occur in it."
              " Explanations ruled out, in order:"]
        L.append("1. **Tokenization context.** Variants of the published data:")
        for v, x in r["variants"].items():
            L.append(f"   - `{v}`: {x['present']:,} tokens in data; changed but absent {x['changed_not_present']:,}; in data but unchanged {x['present_not_changed']:,}")
        if bd:
            L.append(f"   - beyond those variants (cumulative counts of the {bd['extra']:,} explained): " +
                     "; ".join(f"{k}: {v:,}" for k, v in bd["explained_cumulative"].items()) +
                     f" ({bd['pairs_tested']:,} sample pairs joined with 5 separators). **Unexplained: {bd['unexplained']:,}**"
                     f" ({', '.join(f'{k} {v:,}' for k, v in bd['unexplained_categories'].items())}).")
        else:
            L.append("   - joins between samples / message context: not run")
        if sz:
            g = sz["groups"]
            L.append(f"2. **Change size.** The fit reproduces {sz['never_updated_reproduced']:,} vectors exactly (P = {sz['P']}), so any"
                     " changed number is a real change, not decay rounding. Median fraction of numbers changed / median relative"
                     " change: changed-but-absent tokens "
                     f"{g['updated, not in data']['frac_changed'].get('median', 0):.2f} / {g['updated, not in data']['rel_change'].get('median', 0):.4f};"
                     f" tokens in the data once {g['in data once']['frac_changed'].get('median', 0):.2f} / {g['in data once']['rel_change'].get('median', 0):.4f};"
                     f" more than 100 times {g['in data over 100 times']['frac_changed'].get('median', 0):.2f} / {g['in data over 100 times']['rel_change'].get('median', 0):.4f}."
                     " The unexplained changes are the size of ordinary training updates.")
        if os_:
            L.append("3. **Dataset version.** GAIR publishes two LIMO sets (v1, 817 examples; v2, 800); the GitHub copy of v1 has a"
                     " single commit and the HF copy a single upload. Of the changed-but-absent tokens (all variants), the other"
                     " version contains: " + ", ".join(f"{k} {v['covers']:,}" for k, v in os_["covered_by"].items() if k.startswith("limo")) +
                     ". Exploratory, other public reasoning sets: " +
                     ", ".join(f"{k} {v['covers']:,}" for k, v in os_["covered_by"].items() if not k.startswith("limo")) +
                     f" of {os_['extra']:,}. Large sets contain most tokens by size alone, so this does not identify a source.")
        L.append("4. **Control.** The same pipeline gives 0 changed-but-absent tokens on our own runs (above).")
        if bd and bd.get("examples_by_category"):
            L.append("")
            L.append("Decoded examples of changed-but-absent tokens (random, by category): " + "; ".join(
                f"{k}: " + ", ".join("`" + x.replace("`", "'").replace("\n", "\\n") + "`" for x in v[:15])
                for k, v in bd["examples_by_category"].items() if k != "bytes / whitespace"))
        elif bd and bd.get("unexplained_examples"):
            L.append("")
            L.append("Decoded examples of unexplained changed tokens: " +
                     ", ".join("`" + (x[1] if ("\ufffd" in x[2] or not x[2].strip()) else x[2].replace("`", "'").replace("\n", "\\n")) + "`"
                               for x in bd["unexplained_examples"][16:56]))
        L.append("")
        if child == "GAIR/LIMO":
            L += limo_check()
        else:
            L.append("Neutral reading: the released weights were updated on tokens that do not occur in the published training set"
                     " under any tokenization we could reproduce. The published set alone does not produce these weights."
                     " The weights do not show what the other text was or why.")
    (OUT / "PUBLISHED_LIMO.md").write_text("\n".join(L) + "\n")


def limo_check():
    """Independent check from the DeepSpeed optimizer state left in an old GAIR/LIMO revision
    (results/limo_check/summary.json)."""
    p = ROOT / "results" / "limo_check" / "summary.json"
    if not p.exists():
        return []
    d = json.load(open(p))
    o, run, tk, ex, cjk, ev = d["optimizer"], d["run"], d["tokenization_own"], d["published_examples_with_never_updated_tokens"], d["cjk"], d["eval_sets_fully_covered_questions"]
    L = ["### Independent check: the optimizer state of the training run", "",
         f"An earlier revision of the model repository ({d['optimizer_state_rev']}) still holds the DeepSpeed optimizer",
         f"state of the run. Its fp32 master weights round to the released weights for all {o['fp32_master_rounds_to_release_rows']:,} rows,",
         f"and exactly the {o['rows_exp_avg_sq_nonzero']:,} changed token vectors have a nonzero Adam second moment"
         f" (equal to the changed set: {o['equals_changed_rows']}); every other row equals the base. So the {tk['cut16384']['changed_absent']:,}"
         " changed tokens absent from the published set received real gradients.",
         "",
         f"- **One run of about the published size.** Adam step {o['adam_step_all_ranks']} on every rank; {run['num_processes']} processes,"
         f" batch {run['per_device_bs']}, no accumulation, {run['steps_per_epoch']} steps per epoch, so {run['implied_examples']} examples per epoch."
         f" The release is the epoch-{run['epoch']} checkpoint of a planned {run['num_train_epochs']}-epoch run (lr {run['lr']}, weight decay"
         f" {run['weight_decay']}, not resumed). The run size excludes a larger corpus or extra datasets.",
         f"- **Questions match, solutions differ.** All {tk['question_tokens']:,} question tokens changed (0 unchanged). "
         f"{ex['within_16384']} published examples contain solution tokens that never got a gradient (second moment exactly 0, so"
         " not a detection floor; "
         f"{ex['within_4096']} of them within the first 4,096 tokens, {ex['full']} counting the full text).",
         f"- **CJK.** {cjk['changed']:,} of the {cjk['vocab_rows']:,} CJK vocabulary tokens changed; the published text contains"
         f" {cjk['cjk_chars_in_published_text']} CJK characters.",
         "",
         "**Reading.** The released GAIR/LIMO checkpoint (epoch 9 of a 15-epoch run over about 817 examples) received gradient"
         " updates on 16.5k vocabulary tokens, including about 5.4k CJK tokens, that do not occur in the published 817-example"
         " set, while about 200 tokens of the published solutions were never updated. The questions match; the solution texts"
         " used in training differ from the published ones for at least about 60 examples. The run size excludes a larger"
         " corpus. The weights do not show what the other text was or why it differs.",
         "",
         "**No implication of test-set training.** Token sets cannot show that an evaluation question was trained on: a question"
         " counts as covered below only if every one of its tokens changed, which common tokens make easy. Evaluation questions"
         " fully covered by the changed tokens: " + ", ".join(f"{k} {v}" for k, v in ev.items()) + ". These counts are not"
         " evidence of contamination and we make no such claim."]
    return L


if __name__ == "__main__":
    main()
