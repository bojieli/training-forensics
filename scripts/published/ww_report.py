#!/usr/bin/env python3
"""results/published/webworld/*.json -> results/published/WEBWORLD.md"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
W = ROOT / "results" / "published" / "webworld"
data = json.load(open(W / "data_webworld.json"))
cmp_ = json.load(open(W / "compare.json"))
fine = json.load(open(W / "finescan.json"))
M = cmp_["models"]
m8 = M["Qwen/WebWorld-8B"]


def at(m, C):
    return next(x for x in m["cutoff_scan"] if x["cutoff"] == C)


def fs(child, C):
    return next(x for x in fine[child]["scan"] if x["cutoff"] == C)


inf8 = at(m8, 10 ** 9)
c20 = fs("Qwen/WebWorld-8B", 20000)
L = ["# WebWorld (8B, 14B, 32B) vs its published training set", "",
     "Generated by `scripts/published/ww_report.py` from `results/published/webworld/` "
     "(`ww_tokens.py`, `ww_lengths.py`, `ww_compare.py`, `ww_finescan.py`). Method as in [PUBLISHED.md](PUBLISHED.md): every token in a model's vocabulary has its own vector of numbers; a token "
     "that occurs in the training text gets a gradient and its vector changes, a token that does not stays bit-identical to the base "
     "(here no uniform shrink: weight decay, if any, left no trace), and the final token of a sequence gets no gradient.", "",
     "## Models, bases and data", "",
     "- Models: Qwen/WebWorld-8B, -14B and -32B. Their Hugging Face card metadata names Qwen/Qwen3-8B as the base of all three; "
     "the WebWorld GitHub README names Qwen3-8B, Qwen3-14B and Qwen3-32B. The token vectors agree with the README: each model is "
     "compared with the Qwen3 model of its own size (the 14B and 32B vectors have 5,120 numbers, Qwen3-8B's 4,096).",
     f"- Data: `Qwen/WebWorldData`, `WebWorld_Training.jsonl` (52.2 GB), {data['samples']:,} conversations "
     f"(the dataset card says 1,059,348), rendered with the Qwen3 chat template the models ship with and tokenized whole: "
     f"{data['tokens_chat']:,} tokens, {inf8['present']:,} distinct regular vocabulary tokens. Conversations are long: median "
     f"{data['len_quantiles']['0.5']:,} tokens, {data['over']['32768']:,} longer than 32,768, the longest {data['len_quantiles']['1.0']:,}.", "",
     "## Result", "",
     "| model | vocabulary compared | bit-identical | barely changed (<1% of numbers) | updated |", "|---|---|---|---|---|"]
for k, m in M.items():
    L.append(f"| {k} | {m['compared']:,} | {m['bit_identical']:,} | {m['barely']:,} | {m['updated']:,} |")
L += ["", "Regular tokens (special tokens listed separately below), against the published set:", "",
      "| model | text counted | in the data | in the data and changed | in the data, bit-identical | changed, not in the data |",
      "|---|---|---|---|---|---|"]
for k, m in M.items():
    a = at(m, 10 ** 9)
    b = fs(k, 20000)
    L.append(f"| {k} | whole conversations | {a['present']:,} | {a['present_changed']:,} | {a['present_bit_identical']:,} | {a['changed_absent']:,} |")
    L.append(f"| {k} | first 20,000 tokens of each | {at(m, 20000)['present']:,} | {at(m, 20000)['present_changed']:,} | {b['present_bit_identical']:,} | {b['changed_absent']:,} |")
wc = m8["wrong_data_control"]
L += ["",
      f"1. **Nothing outside the published set was updated.** Counting whole conversations, every one of the {inf8['present_changed']:,} "
      "changed regular tokens of WebWorld-8B occurs in the published data ("
      + "; ".join(f"{k.split('-')[-1]}: {at(M[k], 10 ** 9)['changed_absent']} changed tokens not in it" for k in ("Qwen/WebWorld-14B", "Qwen/WebWorld-32B")) + ").",
      f"2. **Almost everything in it was.** {inf8['present_changed']:,} of {inf8['present']:,} regular tokens in the data changed "
      f"({100 * inf8['present_changed'] / inf8['present']:.1f}%). The {inf8['present_bit_identical']:,} that did not mostly occur only "
      f"late in long conversations (median earliest position {m8['bracket']['bit_identical_in_data_earliest_pos_quantiles'][list(m8['bracket']['bit_identical_in_data_earliest_pos_quantiles'])[2]]:,}).",
      "3. **The weights point to a training length limit near 20,000 tokens.** Counting only the first C tokens of each "
      "conversation, the number of changed tokens that are not in the counted text falls steeply up to C = 20,000 "
      f"({fs('Qwen/WebWorld-8B', 19000)['changed_absent']} at 19,000, {c20['changed_absent']} at 20,000) and barely moves after "
      f"({fs('Qwen/WebWorld-8B', 21000)['changed_absent']} at 21,000, {fs('Qwen/WebWorld-8B', 24000)['changed_absent']} at 24,000), "
      f"while the in-data tokens left bit-identical rise faster past it ({c20['present_bit_identical']} at 20,000, "
      f"{fs('Qwen/WebWorld-8B', 21000)['present_bit_identical']} at 21,000). The best single limit in a 250-token scan is 20,000 "
      "at all three sizes. Leaving long conversations out entirely instead of truncating them fits worse "
      f"(best: {m8['best_drop']['present_bit_identical'] + m8['best_drop']['changed_absent']} mismatches against "
      f"{c20['present_bit_identical'] + c20['changed_absent']}).",
      f"4. **The fit is not exact.** At a 20,000 limit, {c20['present_bit_identical']} tokens (0.19% of the data's vocabulary) occur within the "
      f"first 20,000 tokens of some conversation but were never updated, and {c20['changed_absent']} changed tokens occur only later "
      "in their conversations. A different truncation rule, a different tokenization of some conversations, or published conversations "
      f"that were not in the training run (the file holds {data['samples'] - 1059348:,} more conversations than the card's count) would each "
      "produce such a residual; the weights do not tell which. Unlike the s1.1 case there is no clean bracket.",
      f"5. **Same at three sizes.** 8B, 14B and 32B leave {M['Qwen/WebWorld-32B']['bit_identical']:,}-{m8['bit_identical']:,} vectors "
      "bit-identical with nearly the same mismatch counts: consistent with one training set for the series.",
      f"6. **Wrong-data control.** Scored against a set the models were not trained on (s1K-1.1), "
      f"{wc['changed_absent']:,} changed tokens are 'not in the data' instead of {inf8['changed_absent']}.", "",
      "## Special tokens", "",
      f"- Updated: {', '.join('`' + t + '`' for t in m8['special_updated'])} (the chat template inserts an empty `<think>` block in the final assistant turn).",
      f"- Bit-identical: {', '.join('`' + t + '`' for t in m8['special_bit_identical'])}. `<|endoftext|>` unchanged is consistent with one "
      "conversation per sequence (no packing).", "",
      "## Verdict", "",
      "Consistent with the published set: the token vectors of all three WebWorld models changed for the vocabulary of "
      "WebWorldData and for nothing outside it, with the pattern of a training length limit of about 20,000 tokens; a residual of "
      f"about {c20['present_bit_identical'] + c20['changed_absent']} tokens (0.2%) is not explained by a single length limit. The weights say "
      "nothing about why. The card metadata naming Qwen3-8B as the base of the 14B and 32B models reads as a metadata error; the README "
      "and the weights agree."]
(ROOT / "results" / "published" / "WEBWORLD.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
