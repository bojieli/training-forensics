#!/usr/bin/env python3
"""results/roster/sweep.jsonl -> results/roster/SWEEP.md (+ sweep_stats.json)."""
from __future__ import annotations

import collections
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
IN = ROOT / "results" / "roster" / "sweep.jsonl"
SHARDS = [IN, ROOT / "results" / "roster" / "sweep_cml3.jsonl"]
OUT = ROOT / "results" / "roster" / "SWEEP.md"
STATS = ROOT / "results" / "roster" / "sweep_stats.json"


def fam(repo):
    r = repo.lower()
    for k in ("qwen3.5", "qwen3", "qwen2.5", "qwen2", "qwq", "llama-4", "llama", "deepseek", "kimi", "glm", "mistral",
              "mixtral", "gemma", "olmo", "phi", "nemotron", "minimax", "ernie", "internlm", "intern", "hy", "yi",
              "baichuan", "falcon", "granite", "smollm", "pythia", "exaone", "seed", "mimo", "step", "ling", "aquila"):
        if k in r:
            return k
    return r.split("/")[0]


def g(x, fmt="{:.3g}"):
    return "–" if x is None else fmt.format(x)


def main():
    recs = {}
    for f in SHARDS:
        if not f.exists():
            continue
        for line in open(f):
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            old = recs.get(r["key"])
            # prefer analysed rows over errors/skips; otherwise the later line wins
            if old is None or not (old["status"] == "ok" and r["status"] != "ok"):
                recs[r["key"]] = r
    R = list(recs.values())
    ok = [r for r in R if r["status"] == "ok"]
    untied = [r for r in ok if not r["tied"]]
    tied = [r for r in ok if r["tied"]]
    err = [r for r in R if r["status"] == "error"]
    skip = [r for r in R if r["status"].startswith(("skipped", "unsupported"))]

    def E(r, k):
        return r["embed"][k]

    def P_ok(r):     # decay factor is only meaningful when it reproduces a set of unmoved rows
        return E(r, "unmoved") >= 10 and (E(r, "P_exact_frac") or 0) >= 0.5

    def flat_ok(r):  # flat rows whose move is well above one bf16 ulp (~1e-5 at |w|~1e-2)
        D = E(r, "flat_D_q")[2]
        return E(r, "flat") >= 20 and D is not None and (r["dtype_child"] == "F32" or D >= 2e-5)

    same = [r for r in untied if E(r, "moved") == 0 and E(r, "near") == 0]
    has_unmoved = [r for r in untied if E(r, "unmoved") > 0 and E(r, "moved") > 0]
    all_moved = [r for r in untied if E(r, "unmoved") + E(r, "near") == 0]
    decayed = [r for r in untied if P_ok(r) and abs(E(r, "P") - 1) > 1e-6]
    flat = [r for r in untied if flat_ok(r)]

    # control tokens by family (chat fine-tunes)
    ctl = collections.defaultdict(list)
    for r in untied:
        if E(r, "moved") == 0 or E(r, "unmoved") < 10:
            continue                      # every row moved: "touched" carries no information
        sp = [t for t in r.get("special", []) if t["in_parent"]]
        if not sp:
            continue
        touched = tuple(t["content"] for t in sp if t["state"] == "moved")
        ctl[fam(r["child"])].append((r["child"], len(sp), touched))

    st = dict(pairs=len(R), ok=len(ok), untied_ok=len(untied), tied_ok=len(tied), errors=len(err), skipped=len(skip),
              unchanged_embeddings=len(same), with_unmoved_rows=len(has_unmoved), every_row_moved=len(all_moved),
              decoupled_decay_visible=len(decayed), with_flat_rows=len(flat))
    json.dump(st, open(STATS, "w"), indent=1)

    L = []
    w = L.append
    w("# Roster sweep: what the input embeddings of 265 open models say about their fine-tunes\n")
    w("Generated by `scripts/roster/sweep_report.py` from `results/roster/sweep.jsonl` "
      "and `sweep_cml3.jsonl` (`scripts/roster/sweep.py`, two shards). One row per public parent -> child pair from `roster/pairs.json` "
      "whose input embeddings have the same hidden size (common vocabulary rows are compared).\n")
    w("## Aggregate\n")
    w(f"- pairs: {len(R)}; analysed: {len(ok)} ({len(untied)} untied, {len(tied)} tied); errors: {len(err)}; skipped: {len(skip)}")
    w(f"- child embedding bit-for-bit equal to parent (no embedding training, or frozen): **{len(same)}**")
    w(f"- some rows exactly unmoved while others moved (the token-usage record is readable): **{len(has_unmoved)}**")
    w(f"- every common row moved (tied head, vocab-wide training signal, re-initialised or not a fine-tune of this parent): **{len(all_moved)}**")
    w(f"- unmoved rows shrunk by a common factor P < 1 (decoupled weight decay on the embedding): **{len(decayed)}**")
    w(f"- with >= 20 rows consistent with a single Adam touch (flat rows): **{len(flat)}**\n")
    w("Definitions. *unmoved*: every coordinate equals round(P x parent) (fp32: within 64 ulp). "
      "*near*: at most max(2, 1% of d) coordinates differ (rounding of a step-by-step decay, or a tiny move). "
      "*moved*: more. *P*: decay factor fitted on unmoved rows; -ln P = sum over steps of lr_t x wd. "
      "*flat*: a moved row with >= 90% of coordinates changed whose per-coordinate admissible move intervals "
      "(16-bit rounding) or |Delta| (fp32, within 1%) share one value D; D / 31.77 is the learning rate at the "
      "touch step for default Adam betas. In 16-bit releases with large batches few rows are flat; flat D values "
      "near one ulp are not interpretable.\n")

    w("## Control / special tokens touched by fine-tuning (tokens present in the parent)\n")
    w("| family | child | special tokens | touched |\n|---|---|---|---|")
    for f in sorted(ctl):
        for child, n, touched in sorted(ctl[f]):
            t = ", ".join(f"`{x}`" for x in touched[:12]) + (" ..." if len(touched) > 12 else "")
            w(f"| {f} | {child} | {n} | {len(touched)}: {t} |")
    w("")
    # identical patterns inside a family
    w("### Families whose fine-tunes touch the same control tokens\n")
    for f in sorted(ctl):
        pats = collections.Counter(tuple(sorted(x[2])) for x in ctl[f])
        for pat, c in pats.most_common():
            if c >= 2:
                w(f"- {f}: {c} fine-tunes touch the same {len(pat)} tokens: " + ", ".join(f"`{x}`" for x in pat[:10]))
    w("")

    w("## All pairs\n")
    w("| child | parent | dtype | rows | unmoved | near | moved | P | Σlr·wd | flat | flat lr (med) | ctl moved/n | head moved | note |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(R, key=lambda r: (r["status"] != "ok", r.get("tied", False), r["child"])):
        if r["status"] != "ok":
            w(f"| {r['child']} | {r['parent']} | | | | | | | | | | | | {r['status'][:60]} {r.get('error','')[:80]} |")
            continue
        e = r["embed"]
        ss = r.get("special_summary", {})
        h = r.get("head")
        note = []
        if r["tied"]:
            note.append("tied (output gradient reaches every row)")
        if r["shape_parent"] != r["shape_child"]:
            note.append(f"vocab {r['shape_parent'][0]}->{r['shape_child'][0]}")
        if e["moved"] == 0 and e["near"] == 0:
            note.append("embedding unchanged")
        lrm = e["flat_lr_q"][1] if flat_ok(r) else None
        if not P_ok(r) and e["moved"]:
            note.append("no unmoved rows: P not identifiable")
        w(f"| {r['child']} | {r['parent']}{'@'+r['parent_revision'] if r.get('parent_revision') else ''} | "
          f"{r['dtype_parent']}->{r['dtype_child']} | {e['rows']} | {e['unmoved']} | {e['near']} | {e['moved']} | "
          f"{(format(e['P'], '.6g') if P_ok(r) else '–')} | {(g(e['lr_wd_integral']) if P_ok(r) else '–')} | {e['flat']} | {g(lrm)} | "
          f"{(str(ss.get('moved','–'))+'/'+str(ss.get('n','–'))) if E(r,'unmoved')>=10 else '(all moved)'} | {(str(h['moved'])+'/'+str(h['rows'])) if h and 'moved' in h else '–'} | {'; '.join(note)} |")
    w("")
    if err:
        w("## Errors\n")
        for r in err:
            w(f"- {r['key']}: {r.get('error','')[:200]}")
    OUT.write_text("\n".join(L) + "\n")
    print(json.dumps(st))


if __name__ == "__main__":
    main()
