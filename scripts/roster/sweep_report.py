#!/usr/bin/env python3
"""results/roster/sweep.jsonl -> results/roster/SWEEP.md (+ sweep_stats.json).

Internal names: a *row* is one token's vector in the embedding matrix; *unmoved* = bit-identical to
the parent (after the common decay factor P); *moved* = updated. The prose written to SWEEP.md uses
plain terms (see STYLE.md)."""
from __future__ import annotations

import collections
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
IN = ROOT / "results" / "roster" / "sweep.jsonl"
SHARDS = [IN, ROOT / "results" / "roster" / "sweep_cml3.jsonl"]
OUT = ROOT / "results" / "roster" / "SWEEP.md"
STATS = ROOT / "results" / "roster" / "sweep_stats.json"


def fam(repo):
    r = repo.lower()
    for k in ("qwen3.5", "qwen3", "qwen2.5", "qwen2", "qwq", "llama-4", "llama", "deepseek", "kimi", "glm", "mistral",
              "mixtral", "gemma", "olmo", "phi", "nemotron", "minimax", "ernie", "internlm", "intern", "hy", "yi",
              "baichuan", "falcon", "granite", "smollm", "pythia", "exaone", "seed", "mimo", "step", "ling", "aquila"):
        if k in r:
            return k
    return r.split("/")[0]


def g(x, fmt="{:.3g}"):
    return "–" if x is None else fmt.format(x)


def main():
    recs = {}
    for f in SHARDS:
        if not f.exists():
            continue
        for line in open(f):
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            old = recs.get(r["key"])
            # prefer analysed rows over errors/skips; otherwise the later line wins
            if old is None or not (old["status"] == "ok" and r["status"] != "ok"):
                recs[r["key"]] = r
    R = list(recs.values())
    ok = [r for r in R if r["status"] == "ok"]
    untied = [r for r in ok if not r["tied"]]
    tied = [r for r in ok if r["tied"]]
    err = [r for r in R if r["status"] == "error"]
    skip = [r for r in R if r["status"].startswith(("skipped", "unsupported"))]

    def E(r, k):
        return r["embed"][k]

    def P_ok(r):     # decay factor is only meaningful when it reproduces a set of unmoved rows
        return E(r, "unmoved") >= 10 and (E(r, "P_exact_frac") or 0) >= 0.5

    def flat_ok(r):  # flat rows whose move is well above one bf16 ulp (~1e-5 at |w|~1e-2)
        D = E(r, "flat_D_q")[2]
        return E(r, "flat") >= 20 and D is not None and (r["dtype_child"] == "F32" or D >= 2e-5)

    same = [r for r in untied if E(r, "moved") == 0 and E(r, "near") == 0]
    has_unmoved = [r for r in untied if E(r, "unmoved") > 0 and E(r, "moved") > 0]
    all_moved = [r for r in untied if E(r, "unmoved") + E(r, "near") == 0]
    decayed = [r for r in untied if P_ok(r) and abs(E(r, "P") - 1) > 1e-6]
    decayed_real = [r for r in decayed if E(r, "P") > 0]      # P = 0: vectors zeroed, not decayed
    readable = [r for r in has_unmoved if E(r, "unmoved") >= 2]
    single_unmoved = [r for r in has_unmoved if E(r, "unmoved") == 1]
    near_only = [r for r in untied if r not in same and r not in has_unmoved and r not in all_moved]
    flat = [r for r in untied if flat_ok(r)]

    # control tokens by family (chat fine-tunes)
    ctl = collections.defaultdict(list)
    for r in untied:
        if E(r, "moved") == 0 or E(r, "unmoved") < 10:
            continue                      # every row moved: "touched" carries no information
        sp = [t for t in r.get("special", []) if t["in_parent"]]
        if not sp:
            continue
        touched = tuple(t["content"] for t in sp if t["state"] == "moved")
        ctl[fam(r["child"])].append((r["child"], len(sp), touched))

    st = dict(pairs=len(R), ok=len(ok), untied_ok=len(untied), tied_ok=len(tied), errors=len(err), skipped=len(skip),
              unchanged_embeddings=len(same), with_unmoved_rows=len(has_unmoved), every_row_moved=len(all_moved),
              decoupled_decay_visible=len(decayed), with_flat_rows=len(flat),
              readable_token_record=len(readable), exactly_one_unmoved=len(single_unmoved),
              near_only=len(near_only), decay_excluding_zeroed=len(decayed_real))
    json.dump(st, open(STATS, "w"), indent=1)

    L = []
    w = L.append
    w("# Roster sweep: what the token vectors of 265 open models say about their fine-tunes\n")
    w("Every token in a model's vocabulary has its own vector of numbers (its embedding). If a token never "
      "appears in a fine-tune's data, its vector is never updated. Comparing a fine-tuned model with the model it "
      "started from (its *parent*), token by token, therefore shows which tokens the fine-tuning data contained. "
      "Counts below are counts of distinct vocabulary tokens, not amounts of text.\n")
    w("Generated by `scripts/roster/sweep_report.py` from `results/roster/sweep.jsonl` "
      "and `sweep_cml3.jsonl` (`scripts/roster/sweep.py`, two shards). One row per public parent -> child pair from `roster/pairs.json` "
      "whose token vectors have the same length (tokens present in both vocabularies are compared).\n")
    w("## Aggregate\n")
    w(f"- parent -> fine-tune pairs: {len(R)}; analysed: {len(ok)} ({len(untied)} with separate input and output matrices, "
      f"{len(tied)} sharing one matrix for both (tied)); errors: {len(err)}; skipped: {len(skip)}")
    w(f"- every token vector bit-identical to the parent (token vectors not trained, or frozen): **{len(same)}**")
    w(f"- some token vectors bit-identical to the parent while others were updated, so the list of tokens the "
      f"fine-tune data contained is recovered exactly: **{len(readable)}** (plus {len(single_unmoved)} pairs where "
      f"only a single token vector stayed untouched, too few to call a record)")
    w(f"- every token vector changed (tied output layer, a vocabulary-wide training signal, re-initialised vectors, "
      f"or not a fine-tune of this parent): **{len(all_moved)}**")
    w(f"- no vector exactly untouched but a few changed in only 1-2 coordinates (rounding of a step-by-step decay): "
      f"**{len(near_only)}**")
    w(f"- untouched vectors all shrunk by one common factor P < 1 (decoupled weight decay on the token vectors): "
      f"**{len(decayed_real)}** (plus {len(decayed) - len(decayed_real)} where the vectors were set to zero, not decayed)")
    w(f"- with >= 20 tokens whose change has the single-step signature (seen in exactly one optimizer step): **{len(flat)}**\n")
    w("Terms used in the tables (column names keep the short forms). *unmoved* (never updated): every number "
      "in the token's vector equals round(P x parent value) (fp32: within 64 smallest steps). *near*: at most "
      "max(2, 1% of the vector length) numbers differ (rounding of a step-by-step decay, or a tiny update). "
      "*moved* (updated): more. *P*: the shrink factor fitted on the untouched vectors; the total weight decay "
      "applied is -ln P = sum over steps of (learning rate x weight decay), written Σlr·wd. "
      "*flat*: an updated vector with >= 90% of its numbers changed whose changes, allowing for 16-bit rounding "
      "(or within 1% in fp32), all have one size D: the signature of a token seen in exactly one optimizer step. "
      "D / 31.77 estimates the learning rate at that step for default Adam settings. In 16-bit releases trained "
      "with large batches few tokens show it, and D values of about one smallest 16-bit step are not interpretable.\n")

    w("## Special tokens updated by fine-tuning (chat markers, tool-call, thinking, image placeholders; tokens present in the parent)\n")
    w("Only pairs with >= 10 untouched token vectors are listed: when every vector changed, 'updated' carries no "
      "information. An updated special token is in the data unless the vendor rewrote or zeroed it (see NOTES.md, e.g. KAT-Dev).\n")
    w("| family | fine-tune | special tokens | updated |\n|---|---|---|---|")
    for f in sorted(ctl):
        for child, n, touched in sorted(ctl[f]):
            t = ", ".join(f"`{x}`" for x in touched[:12]) + (" ..." if len(touched) > 12 else "")
            w(f"| {f} | {child} | {n} | {len(touched)}: {t} |")
    w("")
    # identical patterns inside a family
    w("### Families whose fine-tunes updated the same special tokens\n")
    for f in sorted(ctl):
        pats = collections.Counter(tuple(sorted(x[2])) for x in ctl[f])
        for pat, c in pats.most_common():
            if c >= 2:
                w(f"- {f}: {c} fine-tunes updated the same {len(pat)} tokens: " + ", ".join(f"`{x}`" for x in pat[:10]))
    w("")

    w("## All pairs\n")
    w("Columns: *vocab* = vocabulary tokens compared; *unmoved / near / moved* = token vectors never updated / "
      "changed in 1-2 numbers / updated; *P*, *Σlr·wd* = shrink factor and total weight decay; *flat* = tokens with "
      "the single-step signature; *special upd/n* = special tokens updated / present; *output upd* = output-layer "
      "vectors updated / total.\n")
    w("| fine-tune | parent | dtype | vocab | unmoved | near | moved | P | Σlr·wd | flat | flat lr (med) | special upd/n | output upd | note |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(R, key=lambda r: (r["status"] != "ok", r.get("tied", False), r["child"])):
        if r["status"] != "ok":
            w(f"| {r['child']} | {r['parent']} | | | | | | | | | | | | {r['status'][:60]} {r.get('error','')[:80]} |")
            continue
        e = r["embed"]
        ss = r.get("special_summary", {})
        h = r.get("head")
        note = []
        if r["tied"]:
            note.append("tied: the output gradient reaches every token vector")
        if r["shape_parent"] != r["shape_child"]:
            note.append(f"vocab {r['shape_parent'][0]}->{r['shape_child'][0]}")
        if e["moved"] == 0 and e["near"] == 0:
            note.append("token vectors unchanged")
        lrm = e["flat_lr_q"][1] if flat_ok(r) else None
        if not P_ok(r) and e["moved"]:
            note.append("no untouched vectors: decay not identifiable")
        w(f"| {r['child']} | {r['parent']}{'@'+r['parent_revision'] if r.get('parent_revision') else ''} | "
          f"{r['dtype_parent']}->{r['dtype_child']} | {e['rows']} | {e['unmoved']} | {e['near']} | {e['moved']} | "
          f"{(format(e['P'], '.6g') if P_ok(r) else '–')} | {(g(e['lr_wd_integral']) if P_ok(r) else '–')} | {e['flat']} | {g(lrm)} | "
          f"{(str(ss.get('moved','–'))+'/'+str(ss.get('n','–'))) if E(r,'unmoved')>=10 else '(all moved)'} | {(str(h['moved'])+'/'+str(h['rows'])) if h and 'moved' in h else '–'} | {'; '.join(note)} |")
    w("")
    if err:
        w("## Errors\n")
        for r in err:
            w(f"- {r['key']}: {r.get('error','')[:200]}")
    OUT.write_text("\n".join(L) + "\n")
    print(json.dumps(st))


if __name__ == "__main__":
    main()
