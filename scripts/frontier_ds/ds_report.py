#!/usr/bin/env python3
"""results/frontier_ds/{deepseek.json, v4_change_shape.json} -> results/frontier_ds/DEEPSEEK.md"""
from __future__ import annotations

import json
import pathlib
import statistics

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "results" / "frontier_ds"


def short(r):
    return r.split("/")[-1].replace("DeepSeek-", "")


def main():
    d = json.load(open(R / "deepseek.json"))
    sh = json.load(open(R / "v4_change_shape.json"))
    A = d["anatomy_v3base"]
    C = {(short(c["parent"]), short(c["child"])): c for c in d["comparisons"] if "error" not in c}
    T = d["barely_threshold"]
    L = []
    w = L.append
    w("# DeepSeek special tokens and reserved placeholder slots")
    w("")
    w("Generated by `scripts/frontier_ds/ds_report.py` from `deepseek.json` (made by `ds_tokens.py`) and "
      "`v4_change_shape.json` (made by `ds_shape.py`). Figure: `fig_b_deepseek_special_tokens.png` (`ds_fig.py`).")
    w("")
    w("Every token in the vocabulary has its own vector of numbers. For each DeepSeek release we compare every special-token")
    w("vector with the same vector in the released base model the release was trained from:")
    w("")
    w("- **bit-identical**: every number is the same. All DeepSeek comparisons show no weight decay on the token vectors")
    w("  (the sweep's fitted shrink is exactly 1), so an unchanged vector received no update large enough to flip a")
    w("  single 16-bit number. For a vector at its random starting size (about 0.51), one optimizer step at a typical")
    w("  post-training learning rate already flips a few percent of its 7,168 numbers, so bit-identical is strong evidence")
    w("  that the token was not in the post-training input.")
    w(f"- **barely changed**: under {100 * T:g}% of the vector's numbers differ (the STYLE.md threshold, the sweep's \"near\").")
    w("- **updated**: more numbers differ. The share of numbers changed is given wherever it matters: a vector with only")
    w("  a few percent of its numbers changed received one or a few tiny updates (a rarely seen token), while trained")
    w("  tokens typically show 50–100%.")
    w("")
    w("We say what changed, never why. Nothing here is a claim about any lab's intent.")
    w("")
    # ---------------- Part A
    w("## 1. The base model: what pretraining left untouched (DeepSeek-V3-Base)")
    w("")
    w(f"The random starting values of V3-Base's token vectors are regenerated exactly from the checkpoint-forensics card "
      f"(normal, std {A['card']['std']}, seed {A['card']['seed']}), so each vector can be compared with its own start. "
      f"A vector at its start has size about {A['expected_norm_at_start']:.3f}.")
    w("")
    w("| group | vectors | still exactly at their start | size (5th / median / 95th pct) | similarity to own start (median) |")
    w("|---|---|---|---|---|")
    lab = dict(ordinary="ordinary vocabulary", placeholder="reserved placeholder slots (`<｜place▁holder▁no▁N｜>`)",
               named="named special tokens", unused="unused slots beyond the tokenizer")
    for k in ("ordinary", "placeholder", "named", "unused"):
        g = A[k]
        n = g["norm_p5_50_95"]
        w(f"| {lab[k]} | {g['n']:,} | {g['at_start_bit_exact']:,} | {n[0]:.2f} / {n[1]:.2f} / {n[2]:.2f} | "
          f"{g['cos_with_start_p5_50_95'][1]:.3f} |")
    w("")
    nd = [t for t in A["named_detail"] if t["at_start"]]
    w("Named special tokens still exactly at their start in V3-Base: " + ", ".join(f"`{t['token']}`" for t in nd) + ".")
    w("")
    pc, oc = A["placeholder_update_pairwise_cos_p5_50_95"], A["ordinary_update_pairwise_cos_p5_50_95"]
    w("**Why are the 800 placeholder vectors about 5x their starting size?** Three explanations, tested:")
    w("")
    w(f"- *Rescaled start* would keep the start's direction (similarity to start = 1). Measured: "
      f"{A['placeholder']['cos_with_start_p5_50_95'][1]:.3f}. Ruled out.")
    w("- *Replaced by fresh random values* would leave no trace of the start (similarity about 0, within ±0.03). "
      f"Measured: {A['placeholder']['cos_with_start_p5_50_95'][0]:.3f}–{A['placeholder']['cos_with_start_p5_50_95'][2]:.3f} "
      "(5th–95th pct), which is what a start of size 0.51 plus an independent change of size about 2.5 gives "
      "(0.51 / 2.54 ≈ 0.20). Ruled out.")
    w(f"- *Start plus a large change*, like ordinary trained tokens (similarity {A['ordinary']['cos_with_start_p5_50_95'][1]:.3f}). "
      "Consistent. Since nothing shrinks or rescales vectors without a gradient here (no weight decay), the change came "
      "from the optimizer, i.e. the placeholders were in the pretraining input.")
    w(f"- The 800 changes point in a shared direction (pairwise similarity median {pc[1]:.2f}, 5th–95th pct {pc[0]:.2f}–{pc[2]:.2f}) "
      f"while changes of random ordinary tokens do not ({oc[1]:.3f}; {oc[0]:.2f}–{oc[2]:.2f}): the placeholders were "
      "updated together, as tokens that appear in the same kind of context would be.")
    w("")
    w("**Verdict: holds-with-wording.** *Article sentence:* \"DeepSeek-V3-Base's 800 reserved placeholder tokens are not "
      "empty: their vectors are about five times their random starting size, the starting values are still inside them, and "
      "the 800 changes share one direction, the signature of tokens that were in the pretraining input. The 465 unused slots "
      "beyond the tokenizer are still exactly at their random start.\"")
    w("")
    # ---------------- Part B claim 1: tool tokens
    w("## 2. DeepSeek tool tokens across the V3 releases")
    w("")
    tool = list(range(128806, 128815))
    w("| release (vs V3-Base unless noted) | " + " | ".join(f"`{t['token'].replace('<｜', '').replace('｜>', '')}`"
                                                    for t in C[('V3-Base', 'V3')]['named_detail'] if t['id'] in tool) + " |")
    w("|---|" + "---|" * len(tool))
    for key in (("V3-Base", "V3"), ("V3-Base", "V3-0324"), ("V3-Base", "R1"), ("V3-Base", "R1-Zero"),
                ("V3.2-Exp-Base", "V3.2")):
        c = C[key]
        m = {t["id"]: t for t in c["named_detail"]}
        w(f"| {key[1]}{'' if key[0] == 'V3-Base' else ' (vs ' + key[0] + ')'} | " +
          " | ".join(f"{m[i]['status']} ({100 * m[i]['frac_changed']:.0f}%)" for i in tool) + " |")
    w("")
    st = {t["id"]: t for t in A["named_detail"]}
    w("All nine tool tokens are still exactly at their random start in V3-Base (" +
      ("yes" if all(st[i]["at_start"] for i in tool) else "NO: " + str([i for i in tool if not st[i]['at_start']])) +
      "), so pretraining never used them and any change comes from post-training. They are added special tokens that the "
      "chat template emits, so the tokenizer can produce them. Percentages = share of the vector's 7,168 numbers that differ.")
    w("")
    w("**Verdict: holds.** *Article sentence:* \"DeepSeek-V3 updated the tool-call tokens but left the four tool-output tokens "
      "bit-identical to the base model; V3-0324 updated all of them; R1 left all nine tool tokens bit-identical, i.e. still "
      "at their random starting values, and so did R1-Zero.\"")
    w("")
    # ---------------- placeholders per release
    w("## 3. Reserved placeholder slots, release by release")
    w("")
    w("| release | vs | placeholders bit-identical / barely changed / updated | unused slots changed | notes |")
    w("|---|---|---|---|---|")
    for (p, ch), c in C.items():
        pcnt = c["placeholder"]["counts"]
        uc = [u for u in c["unused_changed"]]
        note = ""
        ph = c["placeholder_changed"]
        if ph:
            ids = [x["id"] for x in ph]
            blk = sum(1 for i in ids if 128374 <= i <= 128449)
            med = statistics.median(x["change_norm"] for x in ph)
            note = f"changed ids {min(ids)}–{max(ids)}, {blk} in 128374–128449; median change size {med:.4f}"
        if ch == "V3.1-Nex-N1":
            note += "; spans DeepSeek's own V3.1 continuation (Nex-N1 is built on V3.1, not on V3-Base)"
        w(f"| {ch} | {p} | {pcnt['bit-identical']} / {pcnt['barely changed']} / {pcnt['updated']} | "
          f"{len(uc)} | {note} |")
    w("")
    v3 = C[("V3-Base", "V3")]
    blk = sum(1 for x in v3["placeholder_changed"] if 128374 <= x["id"] <= 128449)
    mx = max(x["frac_changed"] for x in v3["placeholder_changed"])
    nupd = v3["placeholder"]["counts"]["updated"]
    w(f"- **V3**: {len(v3['placeholder_changed'])} placeholder vectors differ from the base, all by tiny amounts (at most "
      f"{100 * mx:.1f}% of numbers; {nupd} of them above 1%), {blk} of them in the contiguous block 128374–128449; their "
      "change size is about 1/25,000 of the vector. That is the pattern of a token touched in a handful of steps. "
      "V3-0324 has 96 of these 97 vectors exactly at the base values (it changed the 97th, 128421, itself), so the "
      "V3 vs V3-0324 comparison shows the same 97 vectors (87 above 1%, 10 below).")
    v4 = C[("V4-Pro-Base", "V4-Pro")]
    w(f"- **V4**: in the V4 bases the 800 original placeholder vectors are larger still (median size "
      f"{statistics.median(x['norm_base'] for x in v4['placeholder_changed']):.1f} in V4-Pro-Base). Both DeepSeek V4 "
      "releases (Flash and Pro) updated all 800; the 417 newer placeholder slots (ids from 128847 up) stayed "
      "bit-identical, so this is not a blanket operation on every vector. The third-party Nex-N2.5-Max, trained from the "
      "same V4-Pro-Base, left all 1,217 placeholders bit-identical.")
    rz = C[("V3-Base", "R1-Zero")]
    w(f"- **R1-Zero** changed {len(rz['unused_changed'])} vectors in slots the V3 tokenizer never produces "
      f"(ids {', '.join(str(u['id']) for u in rz['unused_changed'])}; "
      f"{sum(u['status'] == 'updated' for u in rz['unused_changed'])} updated, "
      f"{sum(u['status'] == 'barely changed' for u in rz['unused_changed'])} barely). Those ids can only reach the model "
      "if the training input contained token ids from outside the released tokenizer. Unexplained; reported as an "
      "observation only.")
    w("")
    w("**Verdict: holds-with-wording** (V3: tiny changes, always state the share of numbers changed). *Article sentence:* \"Post-training touches the "
      "placeholders too: DeepSeek's V4 releases updated all 800 original placeholder vectors while a third-party fine-tune "
      "of the same base left every one bit-identical; V3 changed 97 of them by tiny amounts (1–8% of each vector's numbers), 76 in one contiguous block.\"")
    w("")
    # ---------------- V4 named tokens
    w("## 4. DeepSeek V4's named special tokens: trained or overwritten?")
    w("")
    w("The V4 tokenizer adds named tokens including `<｜query｜>`, `<｜authority｜>`, `<｜domain｜>`, `<｜task｜>`, "
      "`<｜political｜>`, `<｜entity｜>`, `<｜title｜>`, `<｜safety｜>`, `<｜answer｜>`, `<｜search｜>`, `<｜action｜>`, "
      "`｜DSML｜`, search/URL tokens, system-prompt markers and vision/table/box tokens (full list in the figure).")
    w("")
    w("| token | V4-Flash vs base | V4-Pro vs base | V4-Pro-0813 vs V4-Pro | Nex-N2.5-Max vs V4-Pro-Base | V4.1-Flash-1017 vs V4.1-Flash |")
    w("|---|---|---|---|---|---|")
    keys = [("V4-Flash-Base", "V4-Flash"), ("V4-Pro-Base", "V4-Pro"), ("V4-Pro", "V4-Pro-0813"),
            ("V4-Pro-Base", "Nex-N2.5-Max"), ("V4.1-Flash", "V4.1-Flash-1017")]
    show = [128821, 128822, 128825, 128826, 128828, 128829, 128830, 128831, 128832, 128833, 128834, 128835, 128836,
            128837, 128838, 128839, 128840, 128842, 128845]
    for i in show:
        cells = []
        name = None
        for k in keys:
            m = {t["id"]: t for t in C[k]["named_detail"]}
            t = m.get(i)
            if t is None:
                cells.append("not in tokenizer")
                continue
            name = name or t["token"]
            s = t["status"]
            if t["status"] != "bit-identical":
                s += f" ({100 * t['frac_changed']:.0f}%, size {t['norm_base']:.2f}→{t['norm_release']:.2f})"
            if any("unrelated" in f for f in t["overwrite_flags"]):
                s += " ×"
            cells.append(s)
        w(f"| `{name}` | " + " | ".join(cells) + " |")
    w("")
    w("× = the start vector is gone from the release vector (see below).")
    w("")
    vp = sh["DeepSeek-V4-Pro-Base -> DeepSeek-V4-Pro"]
    vf = sh["DeepSeek-V4-Flash-Base -> DeepSeek-V4-Flash"]
    grp = ["<｜query｜>", "<｜authority｜>", "<｜domain｜>", "<｜political｜>", "<｜entity｜>", "<｜safety｜>"]

    def gcos(v):
        pc = v["named_change_pairwise_cos"]
        vals = [x for k, x in pc.items() if all(any(g == part.strip() for g in grp) for part in k.split("|", 1)
                                                 if part) and k.split(" | ")[0] in grp and k.split(" | ")[1] in grp]
        return vals

    gp, gf = gcos(vp), gcos(vf)
    w("Tests on `<｜political｜>`, `<｜safety｜>`, `<｜authority｜>` and their neighbours in DeepSeek's releases:")
    w("")
    w("- **Starting point.** In both V4 bases these vectors are at the random starting size (0.50–0.51 in V4-Pro-Base, "
      "0.38–0.39 in V4-Flash-Base, whose vectors have 4,096 numbers): pretraining did not use them. Any change is post-training.")
    w("- **Zeroed, copied, rescaled?** No release vector is zero, none is an exact copy of another token's vector (base "
      "or release), and none is a rescaled copy of its base vector.")
    w("- **Start still inside?** Yes: similarity to the base vector 0.994–1.000 in V4-Pro (change size 0.01–0.05) and "
      "0.983–0.999 in V4-Flash (0.02–0.07); ordinary vocabulary tokens changed by a median 0.058 (V4-Pro) and 0.092 "
      "(V4-Flash). An overwrite with fresh values would remove the start.")
    G = ["<｜query｜>", "<｜authority｜>", "<｜domain｜>", "<｜political｜>", "<｜entity｜>", "<｜safety｜>", "<｜title｜>",
         "<｜task｜>", "<｜answer｜>", "<｜search｜>"]

    def grp_stats(v):
        vals = [x for k, x in v["named_change_pairwise_cos"].items() if k.split(" | ")[0] in G and k.split(" | ")[1] in G]
        hi = v["reference_change_pairwise_cos_p5_50_95"][2]
        return statistics.median(vals), sum(x > hi for x in vals), len(vals), hi

    mp, ap, np_, hp = grp_stats(vp)
    mf, af, nf, hf = grp_stats(vf)
    w(f"- **Structured like training?** Across the ten tokens query/authority/domain/task/political/entity/title/safety/"
      f"answer/search, the changes point in shared directions: {ap} of {np_} pairs (V4-Pro, median similarity {mp:.2f}) "
      f"and {af} of {nf} pairs (V4-Flash, median {mf:.2f}) exceed the 95th percentile ({hp:.2f}) of random pairs of "
      "ordinary tokens. Independent noise or a per-token overwrite would not correlate; tokens that appear in the same "
      "kinds of sequences do.")
    w("- **Shape of the change.** The spread of change sizes across a vector's numbers matches both a trained token and "
      "Gaussian noise (median/mean about 0.84 for all), so this test cannot separate the two at these sizes; it is "
      "reported in `v4_change_shape.json` but not used as evidence.")
    w("- **Two model sizes.** The same pattern holds independently in V4-Flash (4,096 numbers per vector) and V4-Pro "
      "(7,168), and the tokens changed again in the 0731/0813 updates.")
    w("- **Is V4-Pro-Base / V4-Flash-Base the right reference?** Yes. 446 (Pro) and 447 (Flash) token vectors are "
      "bit-identical between base and release in every one of their numbers, including 14–15 named tokens and the 417 "
      "newer placeholder slots; that cannot happen by chance, so each release continues its base. No weight decay "
      "applies (fitted shrink exactly 1), so a changed vector was changed by the optimizer. The sweep's decay-fit score "
      "(91–92%, `RECONCILE.md`) is below 99% only because fewer than 512 vectors are untouched, so its 512-vector sample "
      "must include trained vectors; it is not evidence against descent.")
    w("- **Third party on the same base.** Nex-N2.5-Max left every one of these tokens bit-identical while updating the "
      "chat and tool tokens.")
    w("")
    w("`｜DSML｜` and `<｜action｜>` are different: their release vectors are 9–24 times their starting size and show no "
      "trace of the start (similarity to the base vector between -0.02 and 0.02, where a start plus an independent change "
      "would give about 0.04–0.11). They were either re-initialised before training or trained so heavily that the start "
      "was erased; the weights cannot tell which.")
    w("")
    w("**Verdict: holds-with-wording.** *Article sentence:* \"DeepSeek V4's tokenizer defines tokens such as "
      "`<｜political｜>`, `<｜safety｜>` and `<｜authority｜>`. Pretraining never used them: in both V4 base models they are "
      "still at their random starting size. DeepSeek's own V4-Flash and V4-Pro releases changed them, by amounts of the same "
      "order as ordinary words and in directions shared across the group, which is what training on them looks like rather than "
      "an overwrite. A third-party fine-tune of the same base left them bit-identical. The weights say these tokens were "
      "trained; they say nothing about what for.\"")
    w("")
    w("## Other observations (not article claims)")
    w("")
    w("- Nex-N2.5-Max's chat and tool vectors (`<｜User｜>`, `<｜Assistant｜>`, the tool tokens) shrank uniformly by "
      "0.11–0.14% with only a small further change, while 1,543 other vectors stayed bit-identical: consistent with weight "
      "decay applied only to vectors that received a gradient. V4.1-Flash-1017 shows the same on a few heavily used "
      "vectors (shrink 0.15–0.36%).")
    w("- The earlier editorial note that V4 releases are \"not comparable to their base\" does not hold for this test: "
      "ordinary token vectors keep similarity ≥0.999 to the base (5th percentile), and 4–15 named tokens per V4 comparison "
      "are bit-identical, so the release is a continuation of that base.")
    (R / "DEEPSEEK.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
