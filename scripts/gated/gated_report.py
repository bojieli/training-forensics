#!/usr/bin/env python3
"""results/gated/*.json + results/roster/sweep_gated.jsonl -> results/gated/GATED.md and FIXLOG/gated.md.
Also importable: gated_table(lane) gives the markdown rows the lane reports append."""
import json, pathlib, importlib.util
ROOT = pathlib.Path(__file__).resolve().parents[2]
G = ROOT / "results" / "gated"
SWEEP = ROOT / "results" / "roster" / "sweep_gated.jsonl"
HB = ["0", "<=1%", "1-10%", "10-50%", ">50%"]


def _classifier():
    spec = importlib.util.spec_from_file_location("cmpb", ROOT / "scripts" / "frontier" / "comparability.py")
    C = importlib.util.module_from_spec(spec); spec.loader.exec_module(C)
    return C.classify


def gated_rows(lane=None):
    """Rows for one lane (or all), raw counts plus the comparability class."""
    if not SWEEP.exists():
        return []
    classify = _classifier(); out = []
    for l in open(SWEEP):
        r = json.loads(l)
        if r.get("status") != "ok" or (lane and not any(lane in s for s in r.get("src", []))):
            continue
        e = r.get("embed", {})
        out.append(dict(lane=",".join(s.split(":", 1)[-1] for s in r.get("src", [])), parent=r.get("official_parent") or r["parent"],
                        child=r["child"], mirror=r.get("mirror_used"), unmoved=e.get("unmoved"), near=e.get("near"), moved=e.get("moved"),
                        P=e.get("P"), fit=e.get("P_exact_frac"), tied=bool(r.get("tied")), cls=classify(r),
                        hist=r.get("change_hist", {}).get("frac")))
    return out


def _row(x):
    h = " / ".join(f"{v:.3f}" for v in x["hist"]) if x["hist"] else "-"
    return (f"| {x['parent']} | {x['child']} | {x['unmoved']:,} / {x['near']:,} / {x['moved']:,} | {x['P']:.6g} | {x['fit']:.4g} | "
            f"{'yes' if x['tied'] else 'no'} | {h} | {x['cls']} |")


HDR = ["| base | release | bit-identical / barely changed / updated token vectors | shrink factor P | fit | one matrix for input and output | "
       "share of vectors by fraction of numbers changed (" + " / ".join(HB) + ") | class |", "|---|---|---|---|---|---|---|---|"]


def gated_table(lane):
    rows = gated_rows(lane)
    if not rows:
        return []
    return (["", "## Previously gated comparisons", "",
             "Run after the licences were accepted (2026-11-16); details in results/gated/GATED.md. Raw counts are given with the "
             "comparability class, since the class rule may change and the counts do not.", ""] + HDR + [_row(x) for x in rows])


def main():
    L = ["# Gated models", "",
         "Generated by `scripts/gated/gated_report.py`. Gated repositories need the publisher's licence accepted on the account. "
         "Before that, the token still allowed reading file metadata, including the sha256 of every weight file, which is enough to "
         "check that the open copies used elsewhere are byte-identical to the official releases.", "",
         "## Open copies vs official releases (sha256 of the weight files)", "",
         "| open copy used | official release | weight files identical | files holding the token vectors identical |", "|---|---|---|---|"]
    for r in json.load(open(G / "mirror_hashes_embed.json")):
        if r.get("official"):
            L.append(f"| {r['mirror']} | {r['official']} | {r['safetensors_identical']} / {r['safetensors_official']} | "
                     f"{'yes' if r['embedding_files_identical'] else 'no'} |")
    L += ["", "Every copy used for Llama 2, 3, 3.1, 3.2, 3.3 and 4 holds byte-identical weight files. The two Llama-3.1-405B FP8 "
          "releases are re-packaged (different files), so their 16-bit token vectors were compared value by value with a copy whose "
          "files are byte-identical to Meta's:", ""]
    p = G / "sub405_embed.json"
    if p.exists():
        L += ["| copy used | compared with | official release it matches by sha256 | token vectors bit-identical |", "|---|---|---|---|"]
        for r in json.load(open(p)):
            L.append(f"| {r['substitute']} | {r['reference']} | {r['reference_file_sha256_equals']} | {r['identical_rows']:,} / {r['rows']:,} "
                     f"({'all ' + format(r['values'], ',') + ' values' if r['bit_identical'] else str(r['identical_values']) + ' values'}) |")
    rows = gated_rows()
    L += ["", "## Comparisons run", "",
          "UserLM-2.0's gated Llama base was read through its byte-identical open copy; the rest were run after the licences were "
          "accepted (2026-11-16).", ""] + HDR + [_row(x) for x in rows]
    L += ["", "Readings:",
          "- **Apertus-v1.5-70B:** base -> SFT -> RL -> release form a clean chain: no weight decay on the token vectors (P = 1) and "
          "tens of thousands of bit-identical vectors at every stage. The RL stage leaves the small-update footprint seen in other RL "
          "stages (most changed vectors have under half their numbers changed).",
          "- **tiny-aya (Cohere):** one matrix for input and output, so every vector changes; there is no token record.",
          "- **Hydrogen-1.0:** descends from GLM-5.3 as its card says; 103,828 token vectors bit-identical, no weight decay.",
          "- **UserLM-2.0:** descends from Llama-3.1-8B-Instruct, not the base model."]
    blocked = json.load(open(G / "blocked.json"))
    L += ["", "## Still not available", ""] + [f"- {b['repo']}: {b['needed_for']}" for b in blocked]
    (G / "GATED.md").write_text("\n".join(L) + "\n")
    fl = ROOT / "FIXLOG"; fl.mkdir(exist_ok=True)
    F = ["# Gated lane summary (for the integration pass)", "",
         "Source: results/gated/GATED.md, results/roster/sweep_gated.jsonl. Raw counts are authoritative; `class` is from "
         "scripts/frontier/comparability.py as of this commit and should be recomputed if that classifier changes.", ""] + HDR + [_row(x) for x in rows]
    F += ["", "Lane reports updated: results/frontier_x/FRONTIER_X.md (Apertus), results/y2026_labs/LABS2026.md (tiny-aya, UserLM-2.0), "
          "results/y2026_ft/FT2026.md (Hydrogen-1.0), results/large/LARGE.md (405B copies verified).",
          "README not edited (per coordinator). Suggested README line: \"Gated models: open copies verified byte-identical to official "
          "releases by sha256; previously gated comparisons in results/gated/GATED.md.\""]
    (fl / "gated.md").write_text("\n".join(F) + "\n")
    print("\n".join(L[-30:]))


if __name__ == "__main__":
    main()
