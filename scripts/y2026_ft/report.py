#!/usr/bin/env python3
"""results/y2026_ft/*.json -> results/y2026_ft/FT2026.md (Fork N2: 2026 fine-tunes on 2026 bases)."""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "results" / "y2026_ft"


def J(p):
    p = R / p
    return json.load(open(p)) if p.exists() else None


cands = json.load(open(ROOT / "scripts" / "y2026_ft" / "candidates.json"))
info = {r["id"]: r for r in (J("hf_candidates_info.json") or [])}
EXTRA = [("k2think_v2", "IFM/K2-V2-Instruct", "IFM/K2-Think-V2"),
         ("memt_flash_vs0731", "deepseek-ai/DeepSeek-V4-Flash-0731", "MemTensor/MemT-1.0-Flash"),
         ("intellect31_vs_i3", "PrimeIntellect/INTELLECT-3", "PrimeIntellect/INTELLECT-3.1"),
         ("mirothinker15_vs_base", "Qwen/Qwen3-30B-A3B-Base", "miromind-ai/MiroThinker-v1.5-30B")]
L = ["# 2026 fine-tunes on 2026 bases: what their token vectors show", "",
     "Generated by `scripts/y2026_ft/report.py` (Fork N2). Each fine-tune is compared with the base its model card",
     "names (and, where that fails, with the likelier parent). Wording follows `STYLE.md`: a vocabulary token is",
     "*updated* when more than 1% of the numbers in its vector differ from round(P x base), *barely changed* when 1 number",
     "to 1% of them differ, *bit-identical* when none do. P is the uniform shrink from weight decay (P = 1: none).",
     "Comparability classes as in `scripts/frontier/comparability.py`. Only the input embedding is compared.", "",
     "## Candidates", "",
     "Picked from the Hugging Face API (text-generation models created in 2026 whose card names a base model,",
     "ranked by downloads, likes and trending; quantized / GGUF / MLX / speculative-decoding drafts dropped), favouring",
     "fame, a published training set, and fp32 weights. Labs' releases of their own bases are left to the lab lane.", "",
     "| name | fine-tune | base named on card | likes | downloads | child format | published data |",
     "|---|---|---|---|---|---|---|"]
for n, p, c, ds in cands:
    i = info.get(c, {})
    fmt = ", ".join(k for k, v in (i.get("st_dtypes") or {}).items() if v > 1e6)
    L.append(f"| {n} | {c} | {p} | {i.get('likes', '-')} | {i.get('dl', '-')} | {fmt or '-'} | {ds.replace(';', ', ') or '-'} |")
L += ["", "## Results", "",
      "| name | fine-tune | compared with | class | updated | barely | bit-identical | special tokens updated | notes |",
      "|---|---|---|---|---|---|---|---|---|"]
rows = [(n, p, c) for n, p, c, _ in cands if n != "k2think_v2"] + EXTRA
pr = {}
for n, p, c in rows:
    d = J(f"pairs/{n}.json")
    pr[n] = d
    if d is None:
        L.append(f"| {n} | {c} | {p} | not run | | | | | |")
        continue
    if d.get("status") == "error":
        L.append(f"| {n} | {c} | {p} | error | | | | | {d.get('error', '')[:90]} |")
        continue
    if d.get("cls") == "shared matrix" and d.get("bit_identical") == d.get("vocab_compared"):
        d["cls"] = "unchanged (shared matrix)"
    ss = d.get("special_summary") or {}
    note = []
    if n == "arete27b":
        note.append("token set matches the published answers exactly with the plain-concatenation format "
                    "(results/arete_check); many vectors changed in < 10% of their numbers")
    elif d.get("low_signal"):
        note.append("low signal: many vectors changed in < 10% of their numbers")
    if d.get("dtype_child") == "F32":
        note.append("fp32 release")
    he = d.get("hand_edits") or {}
    if any(he.get(k) for k in ("zeroed", "rescaled")):
        note.append(f"hand edits {he}")
    L.append(f"| {n} | {c} | {p} | {d.get('cls')} | {d.get('updated', 0):,} | {d.get('barely', 0):,} | "
             f"{d.get('bit_identical', 0):,} | {(str(ss.get('updated')) + ' / ' + str(ss.get('n'))) if ss else '-'} | "
             f"{'; '.join(note)} |")

# ------------------------------------------------------------------ findings (numbers read from the JSON files)
A1, A2 = J("audit_arete27b.json"), J("audit_arete27b_step2.json")
NW, MB = J("nanowhale_timing.json"), J("timing_magenticbrain.json")
ok = [n for n, d in pr.items() if d and str(d.get("status", "")).startswith("ok")]
unchanged = [n for n in ok if pr[n]["cls"].startswith("unchanged")]
F = ["", "## Findings", ""]
if A1 and A2:
    F += ["### 1. NousResearch/Arete-27B against its published SFT set (`NousResearch/arete-data-pairs`)", "",
          "Arete-27B's token vectors match its published SFT answers: 99.2% of the vocabulary in the training text was updated "
          "(63,392 of 63,900) and nothing outside it. The published reasoning traces were not trained on, as the dataset card states "
          "(0 of the 9,412 tokens that occur only in the traces were updated). The training text matches a plain concatenation of system "
          "prompt, question and answer without Qwen's chat markers, consistent with the per-example token counts Nous published "
          "(28,886 rows, 26,398,693 tokens); the marker vectors are therefore unchanged. Nous reports 28,886 training examples, 350 fewer "
          "than the published rows; the weights are consistent with a held-out set of that size.", "",
          "Source of the corrected numbers: the independent check in `results/arete_check/` (logs `e_concat.log`, `f_final.log`). "
          "Our first pass (`audit_arete27b*.json`) tokenized with the Qwen chat template; it left 247 updated tokens apparently absent "
          "from the data. These are tokens such as `.Does` and `.What`, formed where the system prompt joins the question in the bare "
          "concatenation, so none remains unexplained.", "",
          "**Pipeline lesson.** Always include the bare-concatenation format (system + prompt + answer + end token, no template) among "
          "the tokenization variants, and use the boundary tokens it creates (e.g. `.Does`, `.What` after `assistant.`) as a fingerprint "
          "of the format the trainer actually used. Chat markers left bit-identical are explained by this format before anything else.", ""]
F += ["### 2. Many popular 2026 fine-tunes leave no token record", "",
      f"- {len(unchanged)} of the {len(ok)} compared releases have an input embedding bit-identical to the base: "
      + ", ".join(sorted(pr[n]['child'] for n in unchanged)) + ".",
      "- This matches the cards where they say it: LoRA on attention or linear layers (Qwable-v1, grug-27b), and refusal-direction "
      "edits ('abliterated', 'heretic', 'derestricted', 'uncensored') that leave the token embedding untouched.",
      "- Shared input/output matrices erase the record: GLB-3D-Coder, NeoHorse-1-4B, VibeThinker-3B and AgentCPM-Explore changed every vector.", ""]
mf, mv = pr.get("memt_flash"), pr.get("memt_flash_vs0731")
if mf and mv:
    F += ["### 3. Lineage", "",
          f"- MemTensor/MemT-1.0-Flash names DeepSeek-V4-Flash as its base: {mf['bit_identical']:,} of its token vectors are bit-identical "
          f"to V4-Flash, but {mv['bit_identical']:,} (plus {mv['barely']:,} barely changed) to DeepSeek-V4-Flash-0731. Consistent with "
          "V4-Flash-0731 as the starting point (V4-Flash -> 0731 itself leaves 1,261 vectors bit-identical, the same count)."]
    i1, i3 = pr.get("intellect31"), pr.get("intellect31_vs_i3")
    if i1 and i3:
        F.append(f"- PrimeIntellect/INTELLECT-3.1 (card base GLM-4.5-Air-Base): not a decayed copy of that base (fit {i1['fit_reproduced']:.3f}); "
                 f"against INTELLECT-3 every vector changed but a pure-shrink fit reproduces {i3['fit_reproduced']:.3f} of the closest vectors: "
                 "consistent with continued training from INTELLECT-3.")
    m1, m2 = pr.get("mirothinker15_30b"), pr.get("mirothinker15_vs_base")
    if m1 and m2:
        F.append(f"- miromind-ai/MiroThinker-v1.5-30B: {m1['bit_identical']:,} vectors bit-identical and {m1['barely']:,} barely changed "
                 f"against Qwen3-30B-A3B-Thinking-2507 (its card base); against Qwen3-30B-A3B-Base none (fit {m2['fit_reproduced']:.3f}).")
    k2 = pr.get("k2think_v2")
    if k2 and k2.get("cls"):
        F.append(f"- IFM/K2-Think-V2 (fp32) is not a decayed copy of IFM/K2-V2-Instruct, the base its card names "
                 f"(every vector changed, fit {k2['fit_reproduced']:.3f}).")
    F.append("")
if NW:
    t = {x["label"]: x for x in NW["tests"]}
    c, li, co = t["card: cosine N=3000 peak=2e-5 warm=150, wd snapped"], t["control: linear"], t["control: constant"]
    F += ["### 4. fp32 releases: the recipe check", "",
          f"- HuggingFaceTB/nanowhale-100m (fp32, SFT on smol-smoltalk; card: 3,000 steps, cosine, peak 2e-5, 5% warm-up): "
          f"{NW['pure_shrink_vectors']:,} of {NW['vocab']:,} token vectors are near-pure shrinks of the base, by {NW['shrink_pct']:.4f}% "
          f"(weight decay about {c['wd']:g} under the card's schedule).",
          f"- Replaying that decay step by step does not reproduce them bit for bit: median error {c['median_rel_err_in_eps']:.0f} fp32 "
          f"steps under the card's cosine schedule, {li['median_rel_err_in_eps']:.0f} under linear, {co['median_rel_err_in_eps']:.0f} under "
          f"constant. The per-vector shrink also varies ({NW['P_spread_q01_q99'][0]:.7f} to {NW['P_spread_q01_q99'][1]:.7f}), which pure "
          "decoupled decay cannot do: these vectors received small updates besides the decay, so no exact replay or timing reading is "
          "possible. The shrink size is consistent with the card's schedule."]
if MB:
    b = MB.get("best", {})
    F.append(f"- microsoft/MagenticBrain (fp32 release of a Qwen3-14B fine-tune): {MB['identical']:,} vectors bit-identical, "
             f"{MB['moved']:,} updated, only {MB['single_touch_vectors']} seen in a single optimizer step. The schedule fit is weak "
             f"(best {b.get('kind')}, {b.get('N')} steps, coverage {b.get('coverage', 0):.2f}); no schedule is claimed.")
F += ["", "### 5. Not done", "",
      "- deep-principle/Hydrogen-1.0 (GLM-5.3): files are gated (HTTP 401) for anonymous access.",
      "- Diffuspace/Clover-35B-A3B-Preview: changed throughout against Qwen3.6-35B-A3B; the base repo it may come from is not public.",
      "- Published-data audits not run: Qwable-9B (its main set, Glint-Research/Fable-5-traces, is gated), WebWorld-8B (52 GB set), "
      "OpenResearcher-30B-A3B (7.5 GB set; feasible next). TeichAI/DavidAU distills and grug-27b: embedding unchanged, nothing to audit.", "",
      "## Article-ready sentences", "",
      "- \"Arete-27B's token vectors match its published SFT answers: 99.2% of the vocabulary in the training text was updated and nothing "
      "outside it. The published reasoning traces were not trained on, as the dataset card states.\"",
      "- \"The weights even show the text format: a plain concatenation of system prompt, question and answer without Qwen's chat markers, "
      "matching the per-example token counts Nous published; the marker vectors are unchanged for that reason.\"",
      "- \"13 of the 32 popular 2026 fine-tunes we compared leave the token embedding bit-identical to the base (LoRA, refusal-direction edits), so "
      "they carry no token record at all.\"",
      "- \"MemT-1.0-Flash's token vectors point to DeepSeek-V4-Flash-0731, not the original V4-Flash its card names, as the starting point.\"",
      "- \"An fp32 release is not enough by itself: nanowhale-100m's never-seen vectors shrank by the amount its card's schedule implies, "
      "but not exactly, so its recipe cannot be replayed bit for bit.\""]
(R / "FT2026.md").write_text("\n".join(L + F) + "\n")
print("\n".join(F))
