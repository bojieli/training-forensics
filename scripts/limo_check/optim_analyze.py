import numpy as np,os,json,torch
D=os.path.expanduser("~/training-forensics/results/limo_check/dl/")
ld=lambda n: np.concatenate([np.fromfile(f"{D}optim/r{r}_{n}.bin",dtype=np.float32) for r in range(32)]).reshape(152064,5120)
limo=np.fromfile(D+"limo.bin",dtype=np.uint16).reshape(152064,5120); base=np.fromfile(D+"q32i.bin",dtype=np.uint16).reshape(152064,5120)
w=ld("w")
wb=torch.from_numpy(w).to(torch.bfloat16).view(torch.int16).numpy().view(np.uint16)
print("fp32 master rounded to bf16 == release: rows equal",int((wb==limo).all(1).sum()),"of 152064; elems equal frac",float((wb==limo).mean()))
basef=torch.from_numpy(base.view(np.int16)).view(torch.bfloat16).float().numpy()
dw=w-basef; del wb
w_changed=(dw!=0).any(1); print("fp32 master != base: rows",int(w_changed.sum()))
v=ld("v"); v_nz=(v!=0).any(1); print("exp_avg_sq nonzero rows",int(v_nz.sum()))
m=ld("m"); m_nz=(m!=0).any(1); print("exp_avg nonzero rows",int(m_nz.sum()))
ch=np.load(D+"changed_mask.npy")
print("bf16-changed:",int(ch.sum()),"| v_nz & ch",int((v_nz&ch).sum()),"| v_nz & ~ch (sub-ulp updates)",int((v_nz&~ch).sum()),"| ch & ~v_nz",int((ch&~v_nz).sum()),"| w_changed==v_nz:",bool((w_changed==v_nz).all()))
np.save(D+"v_nz.npy",v_nz)
vs=v.sum(1); ms=(m.astype(np.float64)**2).sum(1); r=np.where(vs>0,ms/np.maximum(vs,1e-300),np.nan)
np.save(D+"row_stats.npy",np.stack([vs,ms,np.abs(dw).mean(1),np.sqrt((dw.astype(np.float64)**2).sum(1)),(v!=0).mean(1)],1))
# element-wise: within v_nz rows are all 5120 elements nonzero? (uniform perturbation vs gradient)
print("frac of elements nonzero in v among v_nz rows: min/median",float((v[v_nz]!=0).mean(1).min()),float(np.median((v[v_nz]!=0).mean(1))))
print("max |dw| in rows with v==0:",float(np.abs(dw[~v_nz]).max()))
