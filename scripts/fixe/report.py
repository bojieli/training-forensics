#!/usr/bin/env python3
"""results/fixe/*.json -> results/fixe/FIXE.md (Fix-E: reader v2).

Reader v1 = the recipe reader before Fix-E (tag fixc-frozen). Reader v2 =
trainforensics/recipe_v2.py + scripts/controlled/score.py at tag
reader-v2-frozen; v2.1 (tag reader-v2.1) only changes runs the replay does not
confirm (it keeps the move fit's reading, flagged)."""
from __future__ import annotations

import glob
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "results"


def load(p):
    p = pathlib.Path(p)
    return json.load(open(p)) if p.exists() else None


def v1_path(name):
    for d in ("fixc", "controlled", "gaps/scored", "stacks"):
        p = R / d / f"{name}.fp32.json"
        if p.exists():
            return p
    return None


def rec_str(r):
    if not r:
        return "-"
    wd = r.get("wd_snap") or r.get("wd") or 0
    return f"{r['kind']} {r['N']} w{r['warmup']} {(r.get('peak_snap') or r['peak']):.4g} wd{wd:.4g}"


def true_str(t):
    return f"{t['kind']} {t['N']} w{t['warmup']} {t['peak']:g} wd{t['wd']:g}"


def ok_mark(d):
    ok = d["recipe_ok"]
    shape = ok.get("shape_exact")
    if shape is None:
        shape = ok.get("kind") and ok.get("N") and ok.get("warmup")
    fac = ok.get("decay_factors_exact")
    if fac is None and shape and d["recipe_true"]["wd"]:
        wd = (d["recipe_read"].get("wd_snap") or 0)
        fac = abs(wd - d["recipe_true"]["wd"]) < 1e-12
    return bool(shape), fac


def seed_str(d):
    s = d.get("seed") or {}
    if not s:
        return "-"
    return "found" if s.get("found") == s.get("true") else f"missed ({s.get('found')} for {s.get('true')})"


def tok_str(d):
    t = d.get("tokens_replay") or d.get("tokens")
    return f"{t['tp']:,}/{t['tp'] + t['fn']:,} (+{t['fp']:,} fp)" if t else "-"


def place_str(d):
    p = d.get("placement")
    return f"{p['exact']:,} ({p['wrong']:,} wrong)" if p else "-"


def replay_str(d):
    r, r1 = d.get("replay"), d.get("replay_shift1")
    if not r:
        return "-"
    return f"{r['bit_exact']:,} / {r['weights']:,} (+1 step: {r1['bit_exact']:,})" if r1 else f"{r['bit_exact']:,}"


def conf_str(d):
    rs = d.get("replay_select")
    if not rs:
        return "-"
    return f"{rs['conf']:.3f} ({'recovered' if rs['recovered'] else 'not recovered'})"


def row(name, d):
    shape, fac = ok_mark(d)
    return (f"| {name} | {true_str(d['recipe_true'])} | {rec_str(d['recipe_read'])} | {'yes' if shape else '**no**'} | "
            f"{'-' if fac is None else ('yes' if fac else '**no**')} | {conf_str(d)} | {seed_str(d)} | {tok_str(d)} | "
            f"{place_str(d)} | {replay_str(d)} |")


HDR = ("| run | true (kind steps warm-up peak wd) | read | shape exact | decay factors exact | replay confidence | seed | "
       "tokens via replay | documents placed | never-updated weights bit-exact |\n|---|---|---|---|---|---|---|---|---|---|")


def section(title, names, sets, note=""):
    L = [f"## {title}", ""] + ([note, ""] if note else []) + [HDR]
    for n in names:
        for label, path in sets(n):
            d = load(path) if path else None
            if d:
                L.append(row(f"{n} ({label})", d))
    return L


def main():
    L = ["# Fix-E: reader v2 (recipe by bit-exact replay)", "",
         "Generated by `scripts/fixe/report.py`. Reader v1 = before Fix-E (tag `fixc-frozen`); reader v2 = tag "
         "`reader-v2-frozen` (`trainforensics/recipe_v2.py`, `scripts/controlled/score.py`); v2.1 = tag `reader-v2.1`, which "
         "changes only runs the replay does not confirm (it then reports the move fit's reading, flagged).", "",
         "**What changed.** Under decoupled weight decay every never-updated weight goes through fl32(x * fl32(1 - lr_t wd)) once "
         "per step, so a candidate recipe either reproduces those weights bit for bit or it does not. v1 searched the decay over "
         "round values only (1, 1.5, 2, 2.5, 3 ... x 10^k) and the step count over +-3 of the move fit. v2 fits the decay "
         "continuously (a round value is reported only when it reproduces exactly the same factors), chooses the schedule shape "
         "among the move fit's candidates by a pattern search on the fraction of sampled never-updated weights reproduced, and "
         "reports that fraction as a confidence; below 0.95 the recipe is flagged as not recovered (correct recipes reproduce "
         "0.98-1.0). Runs without weight decay are read exactly as before: the replay carries no information there.", "",
         "Columns: *shape exact* = schedule kind, step count and warm-up equal the trainer's; *decay factors exact* = the read "
         "learning rate x weight decay gives the trainer's fp32 decay factor at every step (the weights fix only the product "
         "peak x decay, so a non-round peak or decay is read to the precision of the move fit, ~1e-4, while the factors are exact); "
         "*tokens via replay* = updated tokens found by the bit-exact replay (needs the recipe), false positives in brackets.", ""]
    dev = ["n01_clean_cos", "n02_clean_isqrt", "n03_swap_lin", "n04_swap_cos", "n05_swap_cmin"]
    L += section("1. Development runs (n01-n05, Fix-C fresh runs; they motivated the fix)", dev,
                 lambda n: [("v1", v1_path(n)), ("v2", R / "fixe" / "dev" / f"{n}.fp32.json"),
                            ("v2.1", R / "fixe" / "v21" / f"{n}.fp32.json")],
                 "n04 has no weight decay, so v1 and v2 read it identically (not re-scored); n01 and n04 have 32-bit seeds, "
                 "outside the seed search range 0..99,999.")
    L += [""]
    reg = ["r07_cos_wd", "r08_lin_wd", "r09_const_wd", "r11_lin_410m", "r12_cosmin_wd", "g01_swap_wd", "q7_wd"]
    L += section("2. Regression: every earlier run with weight decay", reg,
                 lambda n: [("v1", v1_path(n)), ("v2", R / "fixe" / "dev" / f"{n}.fp32.json")],
                 "Runs without weight decay take the unchanged v1 path and are not re-scored.")
    L += [""]
    st = ["t01_clip_off", "t02_clip_on", "t04_ga4", "t08_ds_z2_dsopt", "t13_pack", "t16_ddp2_ga4"]
    L += section("3. Regression: training-stack runs (scripts/stacks/score_stack.py on top of the reader)", st,
                 lambda n: [("v1", R / "stacks" / f"{n}.fp32.json"), ("v2", R / "fixe" / "stacks" / f"{n}.fp32.json"),
                            ("v2.1", R / "fixe" / "v21" / f"{n}.fp32.json")],
                 "t08 (DeepSpeed ZeRO-2 with DeepSpeed's own fused AdamW) decays with a kernel whose rounding differs from torch's, "
                 "so the torch replay confirms no shape; v2 then reported an unconfirmed candidate, v2.1 keeps the move fit's reading "
                 "and the stack scorer's kernel-aware refinement recovers it as before.")
    L += [""]
    fr = ["f01_lin", "f02_cos", "f03_cmin", "f04_isqrt"]
    L += section("4. Fresh runs trained after the freeze (tag reader-v2-frozen), scored blind", fr,
                 lambda n: [("v2", R / "fixe" / "fresh" / f"{n}.fp32.json"), ("v2.1", R / "fixe" / "v21" / f"{n}.fp32.json")],
                 "Non-round peak, weight decay, step count (via the number of documents) and warm-up; seeds below 100,000; "
                 "f04 uses inverse_sqrt, outside the reader's five schedule families (`scripts/fixe/runs_fixe.sh`).")
    (R / "fixe" / "FIXE.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
