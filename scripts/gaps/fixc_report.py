#!/usr/bin/env python3
"""Fix-C results (tech review M1, M2, M3, M8, M10) -> results/fixc/FIXC.md. Every number from a JSON file."""
from __future__ import annotations

import glob
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
R = ROOT / "results"


def load(p):
    p = R / p
    return json.load(open(p)) if p.exists() else None


def wo_all():
    d = {}
    for f in sorted(glob.glob(str(R / "controlled" / "weights_only*.json"))):
        d.update(json.load(open(f)))
    return d


def rel(a, b):
    return (a / b - 1) if b else None


def main():
    L = ["# Fix-C: blind scoring without the claimed dataset, fresh runs, membership and audit controls", "",
         "Generated by `scripts/gaps/fixc_report.py`. The reader (`scripts/controlled/score.py`, `trainforensics/blind.py`),",
         "the swap test v2 (`scripts/gaps/swaps.py` rules A-D) and the membership method (`scripts/gaps/membership3.py`)",
         "were tagged `fixc-frozen` before the fresh runs n01-n06 were trained. Scope: single-epoch Pythia fine-tunes of",
         "125-1,000 steps; the reader's hypothesis class is linear, cosine, constant, cosine-to-floor and warmup-stable-decay.", ""]
    # ---- M1 weights-only
    wo = wo_all()
    L += ["## 1. Step count and recipe from the weights alone (M1)", "",
          "`score.py` may replace the weights-only step count by the one implied by the claimed document list and batch",
          "size. Here every run is re-read with `with_data=False` (W0, W1 and the bit-exact replay refinement only).", "",
          "| run | true (kind / N / warm-up / peak / wd) | weights-only read | kind, N, warm-up exact | peak rel. err | data would change N |",
          "|---|---|---|---|---|---|"]
    n_ok = n_tot = 0
    for k in sorted(wo):
        v = wo[k]
        t, r = v["true"], v["read"]
        ok = r["kind"] == t["kind"] and r["N"] == t["N"] and r["warmup"] == t["warmup"]
        fresh = k.startswith("n0")
        if not fresh:
            n_tot += 1; n_ok += ok
        pe = rel(r["peak"], t["peak"])
        L.append(f"| {k}{' (fresh)' if fresh else ''} | {t['kind']} / {t['N']} / {t['warmup']} / {t['peak']:g} / {t['wd']:g} | "
                 f"{r['kind']} / {r['N']} / {r['warmup']} / {r['peak']:.4g} / {r.get('wd_snap') or 0:g} | {'yes' if ok else '**no**'} | "
                 f"{pe:+.2e} | {'yes' if v['data_would_change_N'] else 'no'} |")
    L += ["", f"Pre-existing runs: kind, step count and warm-up exact from the weights alone in **{n_ok} of {n_tot}**.", ""]
    # ---- fresh runs
    L += ["## 2. Fresh runs trained after the freeze (M1, M3)", "",
          "Non-round peak and weight decay, one schedule outside the five families (`inverse_sqrt`), two 32-bit seeds",
          "(outside the seed search range 0..99,999). Scored blind with the frozen reader.", "",
          "| run | true recipe | read recipe | tokens (direct) | tokens (replay) | replay bit-exact (±1 step) | seed (true / found, hits of placed) | swaps v1 caught / false | swaps v2 caught / false (seed confident?) |",
          "|---|---|---|---|---|---|---|---|---|"]
    sw = load("gaps/swaps_v2.json") or {}
    for f in sorted(glob.glob(str(R / "fixc" / "n0*.fp32.json"))):
        d = json.load(open(f)); n = d["run"]
        t, r = d["recipe_true"], d["recipe_read"]
        tk, tr = d["tokens"], d.get("tokens_replay")
        rp, r1 = d.get("replay"), d.get("replay_shift1")
        sd, s1 = d.get("seed") or {}, d.get("swaps") or {}
        s2 = sw.get(n, {})
        L.append(f"| {n} | {t['kind']} {t['N']} w{t['warmup']} {t['peak']:g} wd{t['wd']:g} | {r['kind']} {r['N']} w{r['warmup']} {r['peak']:.4g} wd{(r.get('wd_snap') or 0):.3g} | "
                 f"{tk['tp']:,}/{tk['seen']:,} (+{tk['fp']} fp) | " + (f"{tr['tp']:,}/{tk['seen']:,} (+{tr['fp']:,} fp)" if tr else "-") + " | "
                 + (f"{rp['bit_exact']:,} of {rp['weights']:,} ({r1['bit_exact']:,})" if rp else "- (no decay)") + " | "
                 f"{sd.get('true')} / {sd.get('found')}, {sd.get('hits')} of {sd.get('of')} | {s1.get('caught')}/{s1.get('true')} / {s1.get('false_flags')} | "
                 f"{s2.get('caught')}/{s2.get('true')} / {s2.get('false_flags')} ({'yes' if s2.get('seed_confident') else 'no'}) |")
    L += ["", "Reading: the direct token list (rows that moved above the rounding floor) has no false positives in any",
          "fresh run; the replay-based list is only as good as the recovered recipe, and the replay's bit-exact count is",
          "the check (24.4M of 24.8M when the recipe is right, 28 when it is not). The seed, and with it document",
          "placement and the swap test, failed in all five fresh runs: two seeds lie outside the searched range, one",
          "schedule is outside the hypothesis class, and in the two runs with non-round weight decay the reader snapped",
          "the decay to a round value (0.013 read as 0.015) or misread the step count. Without a seed-confidence gate the",
          "swap test then flags thousands of clean documents.", ""]
    # ---- M2 membership
    L += ["## 3. Membership with the blind recipe, same operating points for every attack (M2)", "",
          "Step curve from the weights-only recipe (section 1), not truth.json. Threshold from the non-members; TPR with a",
          "95% Clopper-Pearson interval; held-out = threshold on half the non-members, TPR on the other half (500 splits).",
          "n06 was trained after the method was frozen.", "",
          "| run | attack | TPR at 0.1% FPR [95% CI] | held-out median [5-95%] | TPR at 0 FP | TPR at 1% FPR |", "|---|---|---|---|---|---|"]
    for n in ("m01", "g05_mem_wiki", "n06_mem_wiki2"):
        d = load(f"gaps/{n}.membership3.blind.json")
        if not d:
            continue
        for a, row in d["operating_points"].items():
            p1, p0, p10 = row["fpr_0.001"], row["fpr_0"], row["fpr_0.01"]
            L.append(f"| {n} | {a} | {100 * p1['full_sample_tpr']:.1f}% [{100 * p1['full_sample_ci95'][0]:.1f}, {100 * p1['full_sample_ci95'][1]:.1f}] | "
                     f"{100 * p1['heldout_tpr_median']:.1f}% [{100 * p1['heldout_tpr_q05_q95'][0]:.1f}, {100 * p1['heldout_tpr_q05_q95'][1]:.1f}] | "
                     f"{100 * p0['full_sample_tpr']:.1f}% | {100 * p10['full_sample_tpr']:.1f}% |")
    L += ["", "LiRA (8 shadow fine-tunes) is more accurate at 0.1% and 1% FPR on every set; this method needs no shadow",
          "training. The zero-false-positive operating point is unstable (set by one or two non-members) and is not the headline.", ""]
    # ---- M10 s1
    L += ["## 4. s1 / s1.1 seed and batch size (M10)", ""]
    for m in ("s1-32B", "s1.1-32B"):
        d = load(f"fp32scan/{m}.seedscan.json")
        if not d:
            continue
        b = d["bootstrap"]
        L.append(f"- **{m}:** {d['rare_tokens']:,} single-document tokens. Best of {d['candidates']:,} (seed 0..2000 x batch 8/16/32): "
                 f"seed {d['top'][0]['seed']}, batch {d['top'][0]['bs']} (misfit {d['top'][0]['misfit']:.3f}; other seeds: median "
                 f"{d['null']['median']:.3f}, best 1% {d['null']['p01']:.3f}, best {d['null']['min']:.3f}). "
                 f"Bootstrap over all single-document tokens ({b['resamples']} resamples): batch 16 best in "
                 f"{100 * b['best_batch_size_share']['16']:.0f}%, seed 42 first in {100 * b['seed42_first_share']:.0f}%. Full scan: `results/fp32scan/{m}.seedscan.npz`.")
    L += ["- **Assumed, not recovered:** cosine schedule with 5% warm-up and beta2 0.95 (from the published sft.sh), 5 epochs,",
          "  and the sampler: accelerate's SeedableRandomSampler (transformers >= 4.36 / accelerate >= 0.25), epoch e order =",
          "  torch.randperm(n) seeded with seed + e. Batch 16 matches the published script; seed 42 is the Trainer default (the",
          "  script sets no seed).", ""]
    # ---- M8
    c = load("published/controls.json")
    L += ["## 5. Published-data audits: matching range and controls (M8)", "", "Full tables: `results/published/CONTROLS.md`.", ""]
    if c:
        for ch, M in c["models"].items():
            ct = M.get("controls", {})
            L.append(f"- **{ch}:** matches at {', '.join(M['matching_variants']) or 'no variant'}; documents with a unique token "
                     f"{100 * ct.get('per_document_share_with_unique_token', 0):.1f}%; leaving out 1% of documents would lose "
                     f"{ct.get('leave_out_1pct', {}).get('expected_tokens_lost', 0):.0f} tokens on average.")
    t = load("large/tulu_controls.json")
    if t:
        s = t["sft"]
        L += ["", f"- **Tulu 3 405B SFT:** against the SFT mixture {s['vs_sft_mixture']['present_not_changed']} in-data tokens bit-identical "
              f"({s['vs_sft_mixture']['present_not_changed_occurring_over_5']} occurring more than 5 times) and "
              f"{s['vs_sft_mixture']['changed_any_not_present_regular']} regular tokens changed (at any change) outside the data; against the "
              f"DPO preference mixture (wrong data) {s['vs_dpo_mixture']['present_not_changed']} / {s['vs_dpo_mixture']['changed_any_not_present_regular']}. "
              f"The SFT mixture covers {s['vs_sft_mixture']['present']:,} of {load('large/tulu_audit.json')['sft']['rows']:,} vocabulary tokens, so 'nothing outside the data' is tested on the remaining "
              f"{load('large/tulu_audit.json')['sft']['rows'] - s['vs_sft_mixture']['present']:,}.",
              f"- **Tulu 3 405B DPO stage** against its own mixture: {t['dpo']['vs_dpo_mixture']['present_not_changed']} in-data tokens bit-identical "
              f"({t['dpo']['vs_dpo_mixture']['present_not_changed_occurring_over_5']} occurring more than 5 times), "
              f"{t['dpo']['vs_dpo_mixture']['changed_any_not_present_regular']} changed outside it: not a token-for-token match. Full 245-token list: `results/large/tulu_controls.json`."]
    (R / "fixc").mkdir(exist_ok=True)
    (R / "fixc" / "FIXC.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
