#!/usr/bin/env python3
"""results/gaps/*.json (+ results/gaps/before/, results/controlled/) -> results/gaps/GAPS.md"""
from __future__ import annotations

import glob
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
G = ROOT / "results" / "gaps"
C = ROOT / "results" / "controlled"
B = G / "before"


def j(p):
    p = pathlib.Path(p)
    return json.load(open(p)) if p.exists() else None


def exact(d):
    if not d:
        return None
    rr, rt = d["recipe_read"], d["recipe_true"]
    return bool(d["recipe_ok"].get("schedule_exact")) and abs((rr.get("wd_snap") or 0) - (rt["wd"] or 0)) < 1e-12


def rec(d):
    r = d["recipe_read"]
    s = f"{r['kind']}/{r['N']}/w{r['warmup']}"
    if r.get("wd_snap"):
        s += f"/wd{r['wd_snap']:.3g}"
    return s


def pl(d):
    p = d.get("placement")
    return f"{p['exact']:,} right, {p['wrong']} wrong" if p else "-"


def sw(d):
    s = d.get("swaps")
    return f"{s['caught']}/{s['true']}, {s['false_flags']} false" if s else "-"


def main():
    L = ["# Closing the gaps to the thread's numbers", "",
         "Generated by `scripts/gaps/gaps_report.py`. Wording follows `STYLE.md`: a token's *embedding* is its vector",
         "of numbers; a token is *updated* when its vector changed in fine-tuning and *bit-identical* when it did not.", ""]

    # ------------------------------------------------------------ 1. re-score
    after = {pathlib.Path(f).name: j(f) for f in sorted(glob.glob(str(C / "*.fp32.json")))}
    before = {pathlib.Path(f).name: j(f) for f in sorted(glob.glob(str(B / "*.fp32.json")))}
    commit = (G / "rescore_commit.txt").read_text().splitlines()[0] if (G / "rescore_commit.txt").exists() else "?"
    L += ["## 1. All controlled runs re-scored with one version of the code", "",
          f"The published per-run results were written at different times (09:18-13:55) by different code versions. Every",
          f"run whose weights are on this machine was re-scored in one batch (`scripts/gaps/rescore.sh`, base commit `{commit[:7]}`",
          "plus the two fixes below). The five Qwen2.5-7B runs were first trained on a borrowed GPU machine whose copy of",
          "the weights was deleted; they were retrained here with the original arguments and seeds and scored with the",
          "same code ('before' = the original machine's result).", "",
          "| run | recipe before | recipe after | placed from weights before | after | with seed (after) | swap check v1 before | after |",
          "|---|---|---|---|---|---|---|---|"]
    nb = na = n = 0
    for k, a in after.items():
        b = before.get(k)
        name = a["run"]
        n += 1
        nb += bool(exact(b)) if b else 0
        na += bool(exact(a))
        L.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
            name, ("exact" if exact(b) else rec(b)) if b else "-", "exact" if exact(a) else "**" + rec(a) + "**",
            pl(b) if b else "-", pl(a), f"{a.get('placement_with_seed', 0):,}/{a['placement']['docs']:,}" if a.get("placement") else "-",
            sw(b) if b else "-", sw(a)))
    L += ["", f"Recipe exact: {nb} of {n} re-scored runs before, **{na} of {n} after**.", ""]
    new = {pathlib.Path(f).name: j(f) for f in sorted(glob.glob(str(G / "scored" / "*.fp32.json")))}
    if new:
        L += ["New runs for this study (Pythia-160m: four with 40 secretly swapped documents, m01 = the membership run):", "",
              "| run | true recipe | recovered | placed from weights | with seed | seed | swap check v1 |", "|---|---|---|---|---|---|---|"]
        for k, a in new.items():
            t = a["recipe_true"]
            L.append(f"| {a['run']} | {t['kind']}/{t['N']}/w{t['warmup']}/{t['peak']:g}" + (f"/wd{t['wd']:g}" if t['wd'] else "") +
                     f" | {'exact' if exact(a) else '**' + rec(a) + '**'} | {pl(a)} | "
                     f"{a.get('placement_with_seed', 0):,}/{a['placement']['docs']:,} | "
                     f"{'recovered' if a['seed']['found'] == a['seed']['true'] else 'missed'} | {sw(a)} |")
        L.append("")

    # ------------------------------------------------------------ 2. r12 and r05
    r12a, r12b = after.get("r12_cosmin_wd.fp32.json"), before.get("r12_cosmin_wd.fp32.json")
    if r12a and r12b:
        L += ["## 2. r12 (cosine to a 0.1x floor, weight decay 0.1): a regression, fixed", "",
              "The schedule search scored its global grid of step counts at the final, very sharp tolerance. A grid point a",
              "few percent off the true 500 steps then scores worse than a wrong long linear schedule whose dense curve covers",
              "every observed update size loosely (scores, lower is better: cosine_min/490 1.09, cosine_min/512 1.04,",
              "linear/5337 0.29, the true cosine_min/500 -0.54). A wider first-pass tolerance (8x) fixed this on the borrowed",
              "GPU machine during the original runs, but that change was lost with its scratch directory, so the published",
              "file shows the broken result. The coarse pass is now in `trainforensics/blind.py::fit_recipe` (`coarse=8`).", "",
              "| r12 | recipe | seed | swap check v1 | tokens by replay (wrong) | bit-exact replay | placed from weights |",
              "|---|---|---|---|---|---|---|"]
        for lab, d in (("before", r12b), ("after", r12a)):
            tr = d.get("tokens_replay") or {}
            L.append(f"| {lab} | {'exact' if exact(d) else rec(d)} | {'recovered' if d['seed']['found'] == d['seed']['true'] else 'missed'} | "
                     f"{sw(d)} | {tr.get('fp', '-'):,} | {d['replay']['bit_exact']:,} of {d['replay']['weights']:,} | {pl(d)} |")
        L.append("")
    r05a = after.get("r05_wsd.fp32.json")
    if r05a:
        L += ["## 3. r05 (warmup-stable-decay): still one step off (not fixed)", "",
              f"r05 is still estimated as {rec(r05a)} for the true wsd/500/w20. In a long constant stage the update sizes of",
              "many steps are identical, so the step count is only bounded to about one step from single-update tokens.",
              "The one-step error shifts every predicted update size slightly, which is what produces r05's",
              f"{r05a['placement']['wrong']} wrong placements and its swap false flags below. A step count implied by the claimed",
              "dataset (N = epochs x ceil(documents / batch)) is computed by `score.py` but this one-step case was not",
              "pursued further.", ""]

    # ------------------------------------------------------------ 4. swaps
    s2 = j(G / "swaps_v2.json") or {}
    if s2:
        L += ["## 4. Swapped documents: v2 test, false flags on every run", "",
              "v1 (`score.py`) flags a claimed document when one of its tokens is bit-identical to the base model, or when",
              "a token only it contains was updated at a different step than the recovered seed puts it in.",
              "v2 (`scripts/gaps/swaps.py`) adds two tests that use the full predicted update history of every token:",
              "a document whose token is shared with later documents but shows a single clean update at a *later* step",
              "(Adam moves a token's vector at full size from its first update, so a real earlier update cannot vanish), and",
              "tokens updated by more than any history inside the claim allows (the largest change of a coordinate is at",
              "most the sum of the single-update sizes of its predicted steps), which points at the step of an unclaimed",
              "document. That last test is reported per training step only: choosing which claimed document of the step was",
              "swapped went 0 right / 3 wrong on s05. With weight decay, *updated* means the token's vector differs from the",
              "bit-exact replay of the recovered decay schedule (this removed v1's false flags on tokens updated so late",
              "that their change is below the generic rounding floor).",
              "v1 numbers are from the re-scored `score.py` output (the retrained Qwen2.5-7B runs included).", "",
              "| run | swapped | v1 caught | v1 false flags | v2 caught | v2 false flags | v2 by rule (caught/false) | steps with an unclaimed update (of which hold a swap / steps holding a swap) |",
              "|---|---|---|---|---|---|---|---|"]
        for name, r in s2.items():
            a = after.get(f"{name}.fp32.json") or j(G / "scored" / f"{name}.fp32.json") or {}
            v1 = a.get("swaps") or {}
            br = ", ".join(f"{k} {v['caught']}/{v['false']}" for k, v in r["by_rule"].items())
            sl = r.get("step_level", {})
            L.append(f"| {name} | {r['true']} | {v1.get('caught', '-')} | {v1.get('false_flags', '-')} | {r['caught']} | "
                     f"{r['false_flags']} | {br} | {sl.get('steps_with_unclaimed_update', '-')} "
                     f"({sl.get('of_which_hold_a_swap', '-')} / {sl.get('steps_holding_a_swap', '-')}) |")
        tot = lambda key, sel: sum(r[key] for r in s2.values() if sel(r))
        L += ["", f"Across runs with swaps: v2 catches {tot('caught', lambda r: r['true'] > 0)} of {tot('true', lambda r: r['true'] > 0)}; "
              f"false flags on clean runs: {tot('false_flags', lambda r: r['true'] == 0)} over "
              f"{sum(1 for r in s2.values() if r['true'] == 0)} runs, of which "
              f"{s2.get('r05_wsd', {}).get('false_flags', 0)} on r05 (its step count is one off, section 3) and "
              f"{tot('false_flags', lambda r: r['true'] == 0 and r['run'] != 'r05_wsd')} on the other "
              f"{sum(1 for r in s2.values() if r['true'] == 0) - 1}; on the swap runs "
              f"{tot('false_flags', lambda r: r['true'] > 0)} false flags against "
              f"{tot('caught', lambda r: r['true'] > 0)} catches. Swaps v2 misses are documents whose every token is shared",
              "with other claimed documents and whose shared tokens show no clean single update.", ""]

    # ------------------------------------------------------------ 5. membership
    m = {nm: j(G / f"{nm}.membership3.json") for nm in ("m01", "g05_mem_wiki")}
    old = j(B / "m01.membership2.json")
    if any(m.values()):
        L += ["## 5. Membership inference (was this document in the training data?), held out", "",
              "Rule: no number below comes from choosing a method or threshold on the documents it is scored on.",
              "The method (exclusion + gradient-sign agreement at the interpolated model state, `scripts/gaps/membership3.py`)",
              "was fixed on m01 (Alpaca) before g05 existed; g05 (Wikipedia text, 4,000 members / 4,000 non-members) was",
              "never used to develop anything. The alarm threshold is the highest score of half the non-members; true",
              "positives and false alarms are counted on the other half (500 random splits).", ""]
        if old and "split_half" in old:
            L += [f"Previously published 41% on m01 was the best of ~20 variants on the full sample. Choosing the variant on",
                  f"half and scoring the other half gives {100 * old['split_half']['heldout_tpr_mean']:.1f}% "
                  f"(5-95%: {100 * old['split_half']['heldout_tpr_q05']:.1f}-{100 * old['split_half']['heldout_tpr_q95']:.1f}%).", ""]
        L += ["Two operating points: threshold = highest calibration non-member (\"zero false alarms\"; held-out false alarms",
              "are then ~1 in 2,000), and threshold = 3rd highest (0.1% false-alarm rate). The zero-alarm number swings with",
              "single outlier non-members, so its median and 5-95% range over splits are both given.", "",
              "| dataset | attack | detected at zero false alarms: median (5-95%) | detected at 0.1% false alarms (median) | held-out false-alarm rate there |",
              "|---|---|---|---|---|"]
        for nm, r in m.items():
            if not r:
                continue
            for an, v in r["attacks"].items():
                sh = v["split_half"]
                L.append(f"| {nm} ({r['source']}, {'development set' if nm == 'm01' else 'held out'}) | {an} | {100 * sh['tpr_median']:.1f}% ({100 * sh['tpr_q05']:.1f}-{100 * sh['tpr_q95']:.1f}) | "
                         f"{100 * sh['tpr_at_0p1pct_fpr_median']:.1f}% | {100 * sh['heldout_fpr_at_0p1pct_mean']:.2f}% |")
        L.append("")
        for nm, r in m.items():
            if r:
                L.append(f"- {nm}: members with at least one token updated in a single step: {r['members_with_single_update_token']:,} of "
                         f"{r['members']:,}; non-members excluded outright: {r['outside_excluded']:,} of {r['outside']:,}; "
                         f"members wrongly excluded: {r['members_excluded_wrongly']}.")
        L += ["", "LiRA here is a strong attacker: 8 shadow fine-tunes on random halves of the exact candidate pool with the",
              "true recipe. At a 0.1% false-alarm rate it beats the embedding method on both datasets; at zero false",
              "alarms it is unstable (a few non-members with extreme scores). The embedding method needs no shadow",
              "training. Its ceiling is the share of members with a token updated in exactly one step. The thread's 64%",
              "at zero false alarms is not reached on either dataset.", ""]

    # ------------------------------------------------------------ 6. epochs
    e = j(G / "epochs_v2.json") or {}
    if not e:
        L += ["## 6. Two epochs", "",
              "Not re-done. A joint two-epoch fit (`scripts/gaps/epochs.py`: the largest change of a token updated once",
              "per epoch equals the sum of its two single-update sizes, 94% within 1% at a 500-step gap and 99.6% at",
              "5,000, measured with the truth) was written but stopped before it finished, when priorities moved to the",
              "re-scoring. The published two-epoch numbers stand.", ""]
    if e:
        L += ["## 6. Two epochs: both updates of a token, jointly", "",
              "A token in one claimed document is updated once per epoch. Splitting its vector's changes into two shades",
              "fails at gaps of a few hundred steps, because Adam's second moment from the first update has not decayed",
              "and the coordinates spread continuously between the shades. What survives at every gap is the top: the",
              "largest change equals the sum of the two single-update sizes (95% of such tokens within 1% at a 500-step gap,",
              "99.6% at 5,000). `scripts/gaps/epochs.py` fits the schedule to those maxima under an E-epoch model (E chosen",
              "by fit), recovers the seed from them (epoch e is shuffled with seed + e), and then predicts both steps of",
              "every token.", "",
              "| run | true | recovered (epochs) | schedule exact | seed | tokens updated exactly twice | both steps right | ...and size matches |",
              "|---|---|---|---|---|---|---|---|"]
        for nm, r in e.items():
            t, rr = r["recipe_true"], r["recipe"]
            L.append(f"| {nm} | {t['kind']}/{t['N']}/w{t['warmup']}/{t['peak']:g} x{t['epochs']:g} | "
                     f"{rr['kind']}/{rr['N']}/w{rr['warmup']}/{rr['peak_snap']:.3g} x{rr['epochs']} | {r['schedule_exact']} | "
                     f"{'recovered' if r['seed'] == r['seed_true'] else 'missed'} | {r['rows_touched_twice']:,} | "
                     f"{100 * r['both_steps_exact_with_seed']:.1f}% | {100 * r['both_steps_exact_and_row_max_matches']:.1f}% |")
        L += ["", "Before (per-token two-shade split, published): both updates within 1% for 0.7% of tokens at a 500-step gap",
              "and 61-69% at 5,000 steps. q7_2ep (Qwen2.5-7B, 2 x 250 steps, only the embedding and output layer trained) is",
              "not recovered by either method: the single-epoch reader gives a wrong schedule and the joint fit finds no",
              "seed (12 hits, at chance level), so no document can be dated. Two-epoch reading remains an open problem.", ""]
    (G / "GAPS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
