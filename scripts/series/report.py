def card(t, W=2500, T=3e12 / 4194304):
    return 3e-4 * t / W if t < W else 3e-5 + 2.7e-4 * 0.5 * (1 + math.cos(math.pi * min(1, (t - W) / (T - W))))
def gh(t, W=5000, T=2e12 / 4194304):
    return 3e-4 * t / W if t < W else 3e-4 * (0.1 + 0.9 * (1 - min(1, (t - W) / (T - W))))
