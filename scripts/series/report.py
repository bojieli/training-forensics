def mean_lr(series, stepf, wd=0.1):
    ck = [c for c in series["checkpoints"] if "error" not in c]
    st = [stepf(c["branch"]) for c in ck]
    out = []
    for i in range(1, len(ck)):
        if st[i] > st[i - 1] and "P" in ck[i] and 0 < ck[i]["P"] <= 1:
            out.append((st[i - 1], st[i], -math.log(ck[i]["P"]) / wd / (st[i] - st[i - 1]), ck[i]["branch"]))
    return out

