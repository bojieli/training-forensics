w("Every token in a model's vocabulary has its own vector of numbers (its embedding). If a token never appears in")
w("training, its vector is never updated by gradients. With decoupled weight decay (AdamW), the vector is still")
w("shrunk at every step by a factor (1 - lr x wd). Between two saved checkpoints, the vector is therefore multiplied")
w("by P = prod(1 - lr_t x wd). We call -ln P (about wd x the sum of the learning rates over those steps) the")
w("**total weight decay applied** in that interval. Given the published weight decay, dividing by wd and by the")
w("number of steps gives the mean learning rate in that interval, with no access to logs.")
w("")
w("Steps: (1) `detect.py` compares an early and a late checkpoint and keeps the token vectors whose late value")
w("is an exact rescaling of the early one (never updated). (2) `series.py` fetches only those vectors from every")
w("checkpoint (HTTP range reads; no full downloads) and measures the shrink factor per interval.")
w("(3) `analyze.py` fits warm-up + cosine / linear / constant schedules and compares with the published recipe.")
